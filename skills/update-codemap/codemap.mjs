// License / copyright boilerplate that leads a file is NOT its purpose. Detect it so the
// purpose derivation skips past the banner to the first real description comment (or the
// filename fallback) instead of surfacing "Copyright (c) ..." as every file's role.
const BOILERPLATE_RE = /\b(copyright|all rights reserved|licen[sc]ed?\b|SPDX-License-Identifier|this (program|file|software) is (free|provided)|redistribut|warranty|GNU (General|Lesser)|Apache License|MIT License|BSD License|Mozilla Public|permission is hereby granted)\b/i;

// A comment line carrying no letters/digits — `*****`, `----`, `====`, `////` rules used
// to frame a banner. Decoration, never a purpose.
const COMMENT_RULE_RE = /^[*#/=_\-~.\s]*$/;

function isBoilerplateComment(text) {
  return BOILERPLATE_RE.test(text) || COMMENT_RULE_RE.test(text);
}

// Lines that come before a file's description comment: shebang, directives,
// C# usings, package/namespace and GDScript class headers. Skipped, not a
// stop. JS/TS/Python imports still stop the scan: a comment after them
// usually documents a member, not the file.
const PREAMBLE_RE = /^(#!|['"]use [a-z ]+['"];?$|using\s+[\w.=\s]+;$|package\s+[\w.]+;?$|namespace\s+[\w.]+\s*[;{]?$|\{$|extends\s|class_name\s|@tool$|#include\s|#pragma\s)/;

// `/// <summary>` style XML doc tags carry no words; keep the text between them.
function stripDocTags(s) {
  return s.replace(/<\/?[a-z]+[^>]*>/gi, '').trim();
}

// `description:` from leading YAML frontmatter (skills, agents, rules, memories).
function frontmatterDescription(headLines) {
  if (!headLines.length || headLines[0].trim() !== '---') return '';
  for (let i = 1; i < headLines.length; i++) {
    const l = headLines[i];
    if (l.trim() === '---') return '';
    const m = l.match(/^description:\s*(.+)$/);
    if (m) return m[1].trim().replace(/^(["'])(.*)\1$/, '$2');
  }
  return '';
}

// Line index just past a leading `---` frontmatter block, else 0.
function frontmatterEnd(headLines) {
  if (!headLines.length || headLines[0].trim() !== '---') return 0;
  for (let i = 1; i < headLines.length; i++) if (headLines[i].trim() === '---') return i + 1;
  return 0;
}

// Top-level `description` of a yaml or json file (eval cases, plugin manifests).
function dataFileDescription(ext, headLines, text) {
  if (ext === '.json') {
    try {
      const j = JSON.parse(text.replace(/^\uFEFF/, ''));
      return j && typeof j.description === 'string' ? j.description : '';
    } catch {
      return '';
    }
  }
  if (ext !== '.yaml' && ext !== '.yml') return '';
  for (let i = 0; i < headLines.length; i++) {
    const m = headLines[i].match(/^description:\s*(.*)$/);
    if (!m) continue;
    const v = m[1].trim();
    if (!/^[|>][-+]?$/.test(v)) return v.replace(/^(["'])(.*)\1$/, '$2');
    const block = [];
    for (let j = i + 1; j < headLines.length && /^\s+\S/.test(headLines[j]); j++) block.push(headLines[j].trim());
    return block.join(' ');
  }
  return '';
}

// The rest of a comment paragraph after its first line, in the same comment style.
// Stops at a blank comment line, a doc tag (`@param`), or the end of the comment.
function commentContinuation(headLines, from, style) {
  const parts = [];
  for (let j = from; j < headLines.length && parts.join(' ').length < PURPOSE_MAX * 2; j++) {
    const l = headLines[j].trim();
    let m = null;
    if (style === '//') m = l.match(/^\/\/\/?\s*(.*)$/);
    else if (style === '#') m = l.match(/^#{1,2}(?![#!])\s*(.*)$/);
    else if (style === '*') m = l.match(/^\*(?!\/)\s*(.*)$/);
    else if (style === '"""') m = l.includes('"""') ? [l, l.replace(/""".*$/, '')] : [l, l];
    if (!m) break;
    const t = stripDocTags(m[1].replace(/\*\/\s*$/, '')).trim();
    if (!t || t.startsWith('@')) break;
    parts.push(t);
    if (/\*\/\s*$/.test(l) || (style === '"""' && l.includes('"""'))) break;
  }
  return parts.join(' ');
}

const ABBREV_RE = /\b(e\.g|i\.e|etc|vs|cf)\.$/i;

// Whole sentences that fit PURPOSE_MAX; a single long sentence is cut at a word.
function clipSentence(s) {
  s = s.replace(/\s+/g, ' ').trim();
  let out = '';
  const re = /[.!?](?=\s|$)/g;
  let m, start = 0;
  while ((m = re.exec(s)) !== null) {
    const end = m.index + 1;
    if (ABBREV_RE.test(s.slice(0, end))) continue;
    const next = s.slice(0, end);
    if (next.length > PURPOSE_MAX) break;
    out = next;
    start = end;
  }
  if (out && (start >= s.length || out.length >= 40)) return clip(out);
  if (s.length <= PURPOSE_MAX) return clip(s);
  const cut = s.slice(0, PURPOSE_MAX - 1);
  const sp = cut.lastIndexOf(' ');
  return (sp > 40 ? cut.slice(0, sp) : cut).replace(/[\s,;:(—-]+$/, '') + '…';
}

// A file's purpose from its own words: frontmatter or data-file description, else the
// first real comment (or markdown heading). Null when the file says nothing.
function derivePurpose(headLines, filename, text = '') {
  const fm = frontmatterDescription(headLines);
  if (fm && !/^[|>][-+]?$/.test(fm)) return clipSentence(fm); // skip block-scalar markers
  const ext = path.extname(filename).toLowerCase();
  const data = dataFileDescription(ext, headLines, text);
  if (data) return clipSentence(data);
  const start = frontmatterEnd(headLines);
  if (ext === '.md' || ext === '.mdx') return markdownPurpose(headLines, start, filename);
  for (let i = start; i < Math.min(headLines.length, start + 20); i++) {
    const l = headLines[i].trim();
    if (!l) continue;
    if (PREAMBLE_RE.test(l)) continue;
    let m, body = null, style = null;
    if ((m = l.match(/^\/\/\/?\s*(.*)$/))) { body = stripDocTags(m[1]) || null; style = '//'; }
    else if ((m = l.match(/^#{1,2}\s+(.+)$/))) { body = m[1].trim(); style = '#'; }
    else if ((m = l.match(/^\/\*\*?\s*(.+?)\s*\*\/$/))) body = m[1].trim();
    else if ((m = l.match(/^\/\*\*?\s*(.+)$/))) { body = m[1].trim(); style = '*'; }
    else if ((m = l.match(/^\*(?!\/)\s*(.+)$/))) { body = m[1].trim(); style = '*'; }
    else if ((m = l.match(/^"""\s*(.+?)"""/))) body = m[1].trim();
    else if ((m = l.match(/^"""\s*(.+)$/))) { body = m[1].trim(); style = '"""'; }
    else if ((m = l.match(/^---\s*$/))) break;
    else if (!l.startsWith('//') && !l.startsWith('#') && !l.startsWith('/*') && !l.startsWith('*')) break;

    if (body !== null) {
      // Skip license/copyright/banner-rule lines; keep scanning for a real description.
      if (isBoilerplateComment(body)) continue;
      const more = style ? commentContinuation(headLines, i + 1, style) : '';
      return clipSentence(more ? `${body} ${more}` : body);
    }
  }
  return null;
}

// A markdown file's first heading, or its first paragraph when the heading only repeats
// the filename (`# Contributing` in CONTRIBUTING.md).
function markdownPurpose(headLines, start, filename) {
  const stem = path.parse(filename).name.toLowerCase().replace(/[-_.\s]+/g, '');
  let heading = null;
  for (let i = start; i < Math.min(headLines.length, start + 40); i++) {
    const l = headLines[i].trim();
    if (!l || /^(```|<|!\[|\||---|===)/.test(l)) continue;
    const h = l.match(/^#{1,6}\s+(.+)$/);
    if (h) {
      const text = h[1].trim();
      if (heading === null && text.toLowerCase().replace(/[-_.\s]+/g, '') !== stem) return clipSentence(text);
      if (heading === null) heading = text;
      continue;
    }
    const para = [l.replace(/^>\s*/, '')];
    for (let j = i + 1; j < headLines.length && headLines[j].trim() && !/^#/.test(headLines[j].trim()); j++) para.push(headLines[j].trim());
    return clipSentence(readmeProse(para.join(' ')));
  }
  return heading !== null ? clipSentence(heading) : null;
}

// Fallback when a file has no description of its own: name its top exports, else
// humanize the filename.
function fallbackPurpose(filename, exports) {
  const names = [];
  for (const e of exports || []) {
    const bare = e.name.replace(/^default:\s+/, '').replace(/\s+—\s+.*$/, '').trim();
    if (bare && !/\s/.test(bare) && !names.includes(bare)) names.push(bare);
  }
  if (names.length) return clip(`Exports ${names.slice(0, 4).join(', ')}${names.length > 4 ? ', …' : ''}`);
  return clip(path.parse(filename).name.replace(/[-_]+/g, ' '));
}

function clip(s) {
  s = s.replace(/[.\s]+$/, '');
  return s.length > PURPOSE_MAX ? s.slice(0, PURPOSE_MAX - 1) + '…' : s;
}

function trimSig(s) {
  s = s.trim().replace(/\s+/g, ' ');
  return s.length > SIGNATURE_MAX ? s.slice(0, SIGNATURE_MAX - 1) + '…' : s;
}

// Drop everything from the first unmatched-context `=` onward.
// Used for `const|let|var|type|enum` exports where the line tail is `= <expr>`
// implementation detail that leaks brackets / commas / quotes into the export name.
function stripRhsValue(rest) {
  const eq = rest.indexOf('=');
  if (eq < 0) return rest;
  // Allow `==` / `=>` / `>=` etc. inside type annotations before the binding `=`:
  // step forward to the first `=` that is not part of a multi-char operator.
  let i = 0;
  while (i < rest.length) {
    if (rest[i] === '=' && rest[i + 1] !== '=' && rest[i + 1] !== '>' && rest[i - 1] !== '!' && rest[i - 1] !== '<' && rest[i - 1] !== '>' && rest[i - 1] !== '=') {
      return rest.slice(0, i);
    }
    i++;
  }
  return rest;
}

// Clip a signature tail at the first unmatched opener of `({[`.
// Keeps balanced groups like `(a, b)` intact, but drops `(` with no closer
// (which is what happens when the declaration spans multiple lines).
function clipUnbalancedTail(s) {
  const stack = [];
  const pairs = { ')': '(', ']': '[', '}': '{' };
  let cut = -1;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === '(' || c === '[' || c === '{') stack.push(c);
    else if (c === ')' || c === ']' || c === '}') {
      if (stack[stack.length - 1] === pairs[c]) stack.pop();
      else { cut = i; break; }
    }
  }
  if (stack.length && cut < 0) {
    // Find the last opener with no closer and cut there.
    let depth = 0;
    for (let i = s.length - 1; i >= 0; i--) {
      const c = s[i];
      if (c === ')' || c === ']' || c === '}') depth++;
      else if (c === '(' || c === '[' || c === '{') {
        if (depth === 0) { cut = i; break; }
        depth--;
      }
    }
  }
  return cut >= 0 ? s.slice(0, cut).replace(/[\s,]+$/, '') : s;
}

function extractExportsTs(text) {
  const out = [];
  const seen = new Set();
  const push = (name) => { if (name && !seen.has(name)) { seen.add(name); out.push({ name }); } };

  const re = /^export\s+(?:default\s+)?(?:async\s+)?(function\*?|class|interface|type|enum|const|let|var)\s+([A-Za-z_$][\w$]*)([^\n]*)/gm;
  let m;
  while ((m = re.exec(text)) !== null) {
    const kind = m[1], name = m[2], rest = m[3];
    const isDefault = /^export\s+default/.test(m[0]);
    // Value bindings: drop RHS entirely so `= z.object({...` doesn't leak in.
    const isValueBinding = kind === 'const' || kind === 'let' || kind === 'var' || kind === 'type' || kind === 'enum';
    let tail = isValueBinding ? stripRhsValue(rest) : rest.replace(/\{.*$/, '');
    tail = clipUnbalancedTail(tail);
    const sig = trimSig(tail);
    push((isDefault ? `default: ${name}` : name) + (sig ? ` — ${sig}` : ''));
  }
  const defAnon = /^export\s+default\s+(?:async\s+)?function\s*\(([^)]*)\)/gm;
  while ((m = defAnon.exec(text)) !== null) {
    push(`default: <anonymous>(${trimSig(m[1])})`);
  }
  const grouped = /^export\s*\{([^}]+)\}/gm;
  while ((m = grouped.exec(text)) !== null) {
    for (const part of m[1].split(',')) {
      const p = part.trim();
      if (!p) continue;
      const asMatch = p.match(/^[A-Za-z_$][\w$]*\s+as\s+([A-Za-z_$][\w$]*)/);
      push(asMatch ? asMatch[1] : p.replace(/\s+as\s+default\s*$/, '').trim());
    }
  }
  const star = /^export\s*\*\s*from\s*['"]([^'"]+)['"]/gm;
  while ((m = star.exec(text)) !== null) push(`re-exports from ${m[1]}`);
  return out;
}

