function inferModuleRole(modName, items) {
  const hardcoded = ROLE_BY_MODULE_NAME[modName];
  if (hardcoded) return hardcoded;
  // Fallback: derive from highest-inbound-edge file's purpose, else humanize the folder name.
  if (items.length) {
    const sorted = [...items].sort((a, b) => (b.inboundCount || 0) - (a.inboundCount || 0));
    if (sorted[0] && sorted[0].purpose && sorted[0].purpose !== '<vendored>') return sorted[0].purpose;
  }
  return modName.replace(/\/$/, '').replace(/[-_]+/g, ' ');
}

function inferModulePurpose(items, inboundCounts) {
  // 2-3 most-imported files' purposes, concatenated. Falls back to top-by-export-count.
  const ranked = items
    .map((it) => ({ ...it, _in: inboundCounts.get(it.rel) || 0 }))
    .filter((it) => it.purpose && it.purpose !== '<vendored>')
    .sort((a, b) => b._in - a._in || (b.exports?.length || 0) - (a.exports?.length || 0));
  const top = ranked.slice(0, 3).map((it) => it.purpose);
  // Dedupe purpose lines; some files share the same one-liner.
  const seen = new Set();
  const unique = [];
  for (const p of top) {
    const k = p.toLowerCase();
    if (seen.has(k)) continue;
    seen.add(k);
    unique.push(p);
  }
  return unique.join('. ');
}

// A module is markdown-dominant when most of its files are .md (a rule/doc corpus, e.g.
// architectural-rules/ or docs/). For these, the per-file purpose derivation scrapes the
// first `#` heading or frontmatter of each rule as if it were a code-doc comment, so the
// aggregated folder summary becomes leaked rule content ("typing. lifecycle. …") instead of
// a description of the folder. Summarise by role (humanised name + file count) instead.
const MARKDOWN_DOMINANT_RATIO = 0.6;
function isMarkdownDominant(items) {
  if (!items.length) return false;
  const md = items.filter((it) => path.extname(it.rel).toLowerCase() === '.md').length;
  return md / items.length >= MARKDOWN_DOMINANT_RATIO;
}
function markdownFolderRole(modName, items) {
  const name = modName.replace(/\/$/, '').replace(/[-_]+/g, ' ');
  const n = items.length;
  return `${name} — ${n} ${n === 1 ? 'file' : 'files'}`;
}

function findModuleEntry(modName, items, entryPoints) {
  const inModule = entryPoints.find((e) => moduleOf(e.rel) === modName);
  if (inModule) return inModule.rel;
  const candidates = ['index.ts', 'index.js', 'index.mjs', 'Boot.cs', 'Main.cs', 'Program.cs'];
  for (const c of candidates) {
    const direct = items.find((it) => path.posix.basename(it.rel) === c && it.rel.split('/').length === 2);
    if (direct) return direct.rel;
  }
  return '';
}

function computeInboundCounts(fileEdges) {
  const inbound = new Map();
  for (const targets of fileEdges.values()) {
    for (const t of targets) inbound.set(t, (inbound.get(t) || 0) + 1);
  }
  return inbound;
}

function computeModuleImportedBy(moduleEdges) {
  const inv = new Map();
  for (const [from, bucket] of moduleEdges.entries()) {
    for (const to of bucket.keys()) {
      if (!inv.has(to)) inv.set(to, new Set());
      inv.get(to).add(from);
    }
  }
  return inv;
}

function publicSurfaceForModule(items, inboundCounts) {
  // Rank files by inbound, take exports[0..2] from each. Cap at 10 total entries.
  const ranked = [...items]
    .filter((it) => it.exports && it.exports.length)
    .map((it) => ({ ...it, _in: inboundCounts.get(it.rel) || 0 }));
  const hasEdges = ranked.some((it) => it._in > 0);
  ranked.sort((a, b) => hasEdges
    ? (b._in - a._in) || a.rel.localeCompare(b.rel)
    : a.rel.localeCompare(b.rel));
  const surface = [];
  const seenName = new Set(); // dedupe on the bare name, keep the signature-bearing form
  for (const it of ranked) {
    for (const e of it.exports.slice(0, 3)) {
      // Keep the callable SIGNATURE (the ` — sig` tail) — it's the single
      // highest-signal element of a public surface: the model learns the API
      // well enough to call it without reading the implementation (retrieval-efficiency tuning).
      // Only strip the `default: ` prefix, which is rendering noise.
      const display = e.name.replace(/^default:\s+/, '');
      const bareName = display.replace(/\s+—\s+.*$/, '');
      if (seenName.has(bareName)) continue;
      seenName.add(bareName);
      surface.push(display);
      if (surface.length >= 10) break;
    }
    if (surface.length >= 10) break;
  }
  return surface;
}

function computeInternals(modName, items, inboundCounts) {
  // Group files by immediate sub-folder (between modName/ and basename).
  // Emit only sub-folders with ≥2 files.
  const bySubfolder = new Map();
  for (const it of items) {
    const rest = it.rel.slice(modName.length); // strips "module/"
    const parts = rest.split('/');
    if (parts.length < 2) continue; // file is directly in module/
    const sub = parts[0];
    if (!bySubfolder.has(sub)) bySubfolder.set(sub, []);
    bySubfolder.get(sub).push(it);
  }
  const lines = [];
  const sortedSubs = [...bySubfolder.keys()].sort();
  for (const sub of sortedSubs) {
    const subItems = bySubfolder.get(sub);
    if (subItems.length < 2) continue;
    const topItem = [...subItems].sort((a, b) => (inboundCounts.get(b.rel) || 0) - (inboundCounts.get(a.rel) || 0))[0];
    const purpose = topItem && topItem.purpose && topItem.purpose !== '<vendored>'
      ? topItem.purpose
      : `${subItems.length} files`;
    lines.push(`${modName}${sub}/ — ${purpose}`);
  }
  return lines;
}

// ----- Retrieval-efficiency helpers (retrieval-efficiency tuning) -----
// Cheap token estimate: ~4 chars/token is the standard rough heuristic. Used only
// to drive --map-tokens truncation, never for anything that must be exact.
function estimateTokens(text) {
  return Math.ceil(text.length / 4);
}

// Module-level importance = sum of inbound file-edges over the module's files.
// Degree-centrality proxy for PageRank (inbound-degree proxy first,
// full PageRank deferred). Drives both module ordering and the ranked Map table.
function computeModuleImportance(groups, inboundCounts) {
  const score = new Map();
  for (const [modName, items] of groups.entries()) {
    let s = 0;
    for (const it of items) s += inboundCounts.get(it.rel) || 0;
    score.set(modName, s);
  }
  return score;
}

// Order module names by importance desc, then alphabetically. Used for the prose
// `## Modules` section so the most-depended-on modules lead (hub-first ordering).
function modulesByImportance(groups, moduleImportance) {
  return [...groups.keys()].sort(
    (a, b) => (moduleImportance.get(b) || 0) - (moduleImportance.get(a) || 0) || a.localeCompare(b));
}

// Build the symbol→file index: exported/public symbol name → defining file (the
// symbol index). The literal "where is X" lookup. Ranked by the defining file's inbound
// count so the most-used symbols survive truncation. Bare names only (signatures live
// in the module surface + File deps); deduped, first definer wins on collision.
function buildSymbolIndex(groups, inboundCounts) {
  const seen = new Set();
  const entries = [];
  for (const items of groups.values()) {
    for (const it of items) {
      if (it.vendored || !it.exports || !it.exports.length) continue;
      const fileRank = inboundCounts.get(it.rel) || 0;
      for (const e of it.exports) {
        const bare = e.name.replace(/^default:\s+/, '').replace(/\s+—\s+.*$/, '').trim();
        // Skip non-symbol pseudo-exports (re-export markers carry spaces / 'from').
        if (!bare || /\s/.test(bare) || bare.startsWith('<')) continue;
        if (seen.has(bare)) continue;
        seen.add(bare);
        entries.push({ name: bare, file: it.rel, rank: fileRank });
      }
    }
  }
  entries.sort((a, b) => b.rank - a.rank || a.name.localeCompare(b.name));
  return entries;
}

// What the size cap removes first, least valuable first. `line` drops tail rows, `block`
// drops tail `- ` entries with their indented sub-lines, `h3` drops tail `### ` blocks,
// `section` empties the whole section, `exports` and `files` thin the per-module file
// listings (see trimListings). `floor` is the first line index (0 = the heading) a trim may remove.
// Sections are pre-sorted by importance, so the tail is the least-used part.
// Everything trimmed here is in codemap.json in full; the Overview, Map, Recent activity,
// Entry points, Layers and Dependencies always stay.
const TRIM_ORDER = [
  { heading: '## Class graph', unit: 'block', floor: 1, what: 'least-imported classes' },
  { heading: '## Call sequence', unit: 'section' },
  { heading: '## References', unit: 'line', floor: 1 },
  { unit: 'exports' },
  { heading: '## Symbol index', unit: 'line', floor: 1 },
  { heading: '## Call graph', unit: 'section' },
  { heading: '## File deps', unit: 'section' },
  { heading: '## Conventions detected', unit: 'line', floor: 1, what: 'least-used conventions' },
  { heading: '## Hubs', unit: 'line', floor: 1 },
  { unit: 'files' },
  { heading: '## Modules', unit: 'h3', floor: 1, what: 'least-used modules' },
];

const LEFT_OUT = '_Left out to fit the size cap; .claude/codemap.json has it._';

// Trim the rendered document to ~mapTokens following TRIM_ORDER, leaving a note in each
// trimmed section. `rank` maps a file to its importer count (least-imported go first) and
// `isGroup` tells a per-module listing heading from a named section. Logs when even the
// fully trimmed document is still over budget.
function truncateToBudget(out, mapTokens, args, log, rank, isGroup) {
  const budget = mapTokens * 4; // estimateTokens is chars / 4
  const parts = out.split(/\n(?=## )/);
  let len = out.length;
  const dropped = {};
  for (const rule of TRIM_ORDER) {
    if (len <= budget) break;
    if (rule.unit === 'exports' || rule.unit === 'files') {
      const res = trimListings(parts, isGroup, rank, len - budget, rule.unit);
      len -= res.saved;
      if (res.removed) dropped[`file listings (${rule.unit === 'files' ? 'files' : 'export lines'})`] = res.removed;
      continue;
    }
    const ix = parts.findIndex((p) => p.startsWith(rule.heading + '\n'));
    if (ix < 0) continue;
    if (rule.unit === 'section') {
      const kept = `${rule.heading}\n${LEFT_OUT}\n`;
      len -= parts[ix].length - kept.length;
      parts[ix] = kept;
      dropped[rule.heading] = 'all';
      continue;
    }
    const lines = parts[ix].split('\n');
    let count = 0;
    while (len > budget) {
      let last = lines.length - 1;
      while (last > 0 && !lines[last].trim()) last--;
      let first = last;
      if (rule.unit === 'block') while (first > 0 && !lines[first].startsWith('- ')) first--;
      if (rule.unit === 'h3') {
        while (first > 0 && !lines[first].startsWith('### ')) first--;
        if (lines.slice(1, first).every((l) => !l.startsWith('### '))) break; // keep the first module
      }
      if (first < rule.floor || first === 0) break;
      const removed = lines.splice(first, last - first + 1);
      len -= removed.join('\n').length + 1;
      count++;
    }
    if (!count) continue;
    dropped[rule.heading] = count;
    const note = `_${count} ${rule.what || 'rows'} left out to fit the size cap; .claude/codemap.json has all of them._`;
    lines.splice(1, 0, note);
    len += note.length + 1;
    parts[ix] = lines.join('\n');
  }
  out = parts.join('\n');
  const summary = Object.entries(dropped).map(([h, n]) => `${n} from ${h.replace('## ', '')}`).join(', ');
  if (summary) log(args, `--map-tokens ${mapTokens}: trimmed ${summary} (~${estimateTokens(out)} tokens)`);
  if (out.length > budget) log(args, `--map-tokens ${mapTokens}: still ~${estimateTokens(out)} tokens after trimming everything trimmable`);
  return out;
}

// Thin the per-module `## <dir>/` listings in place until about `excess` chars are saved,
// least-imported files first: `mode` 'exports' drops `exports:` sub-lines,
// 'files' drops whole file bullets. Each thinned module gets a note line saying what is gone.
function trimListings(parts, isGroup, rank, excess, mode) {
  const NOTE = 100; // rough length of the note line a thinned module gets
  const groups = [];
  for (let i = 0; i < parts.length; i++) {
    const nl = parts[i].indexOf('\n');
    if (!isGroup(parts[i].slice(3, nl))) continue;
    const g = { ix: i, heading: parts[i].slice(0, nl), files: [], note: null, touched: false };
    for (const line of parts[i].split('\n').slice(1)) {
      const m = line.match(/^- `([^`]+)`/);
      if (m) g.files.push({ rel: m[1], bullet: line, exports: null, keep: true, g, at: g.files.length });
      else if (g.files.length && line.startsWith('  exports:')) g.files[g.files.length - 1].exports = line;
      else if (/^_.+_$/.test(line)) g.note = line; // an earlier pass's note
    }
    groups.push(g);
  }
  // Among equally imported files, the tails of the longest listings go first, so every
  // module keeps its first files.
  const order = groups.flatMap((g) => g.files)
    .sort((a, b) => (rank.get(a.rel) || 0) - (rank.get(b.rel) || 0) || b.at - a.at || b.rel.localeCompare(a.rel));
  let est = 0, removed = 0;
  for (const f of order) {
    if (est >= excess) break;
    if (mode === 'exports' && !f.exports) continue;
    if (!f.g.touched) { f.g.touched = true; est -= NOTE; }
    est += (mode === 'files' ? f.bullet.length + 1 : 0) + (f.exports ? f.exports.length + 1 : 0);
    if (mode === 'files') f.keep = false;
    f.exports = null;
    removed++;
  }
  let saved = 0;
  for (const g of groups) {
    if (!g.touched) continue;
    const kept = g.files.filter((f) => f.keep);
    const note = kept.length < g.files.length
      ? `_${g.files.length - kept.length} of ${g.files.length} files left out to fit the size cap; .claude/codemap.json lists all._`
      : (g.note || '_Exports left out to fit the size cap; .claude/codemap.json has them._');
    const body = kept.flatMap((f) => (f.exports ? [f.bullet, f.exports] : [f.bullet]));
    const next = `${g.heading}\n${note}\n${body.map((l) => l + '\n').join('')}`;
    saved += parts[g.ix].length - next.length;
    parts[g.ix] = next;
  }
  return { saved, removed };
}

function detectConventions(groups) {
  // Evidence-based: only fire for ≥3-instance explicit markers (implements/extends/attribute).
  const impl = new Map();   // interface -> [{name, file}]
  const ext = new Map();    // base class -> [{name, file}]
  const attr = new Map();   // attribute -> [{name, file}]

  for (const items of groups.values()) {
    for (const it of items) {
      if (!it.classes) continue;
      for (const c of it.classes) {
        for (const i of (c.implements || [])) {
          const key = normalizeTypeRef(i);
          if (!impl.has(key)) impl.set(key, []);
          impl.get(key).push({ name: c.name, file: it.rel });
        }
        for (const e of (c.extends || [])) {
          const key = normalizeTypeRef(e);
          if (!ext.has(key)) ext.set(key, []);
          ext.get(key).push({ name: c.name, file: it.rel });
        }
        for (const a of (c.attributes || [])) {
          if (!attr.has(a)) attr.set(a, []);
          attr.get(a).push({ name: c.name, file: it.rel });
        }
      }
    }
  }

  const conventions = [];
  const examplesOf = (entries) => entries.slice(0, 3).map((e) => `\`${e.name}\``).join(', ');

  for (const [iface, entries] of impl.entries()) {
    if (entries.length < 3) continue;
    if (!iface) continue;
    conventions.push({
      kind: 'implements',
      name: `Implements ${iface}`,
      count: entries.length,
      detail: `tool/handler convention, e.g. ${examplesOf(entries)}`,
    });
  }
  for (const [base, entries] of ext.entries()) {
    if (entries.length < 3) continue;
    if (!base) continue;
    if (/^(Error|Exception|object)$/.test(base)) continue;
    conventions.push({
      kind: 'extends',
      name: `Extends ${base}`,
      count: entries.length,
      detail: `subclass family, e.g. ${examplesOf(entries)}`,
    });
  }
  for (const [a, entries] of attr.entries()) {
    if (entries.length < 3) continue;
    conventions.push({
      kind: 'attribute',
      name: `Carries [${a}] attribute`,
      count: entries.length,
      detail: `reflection-discoverable marker, e.g. ${examplesOf(entries)}`,
    });
  }

  conventions.sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
  return conventions;
}

async function main() {
  const args = parseArgs(process.argv);
  const root = args.root;
  if (!fs.existsSync(root)) { console.error(`root not found: ${root}`); process.exit(1); }

  log(args, `root: ${root}`);
  const projectName = readProjectName(root);
  log(args, `project: ${projectName}`);

  const config = loadConfig(root);
  const configRegexes = config.skipPatterns.map(configGlobToRegex);
  if (config.skipPatterns.length) log(args, `config: ${config.skipPatterns.length} skip patterns`);

  // Scoped-run guard: if root is a subfolder of a larger repo, warn about ancestor
  // .gitignore / codemap.config.md the per-dir walk can't see (and list nested ones honoured).
  checkScopeContext(root, args);

  // walk() honours .gitignore per-directory (root + nested) as the primary build-output
  // denoise — SKIP_DIRS only catches the standard names; a project's non-standard or nested
  // build dir (e.g. mcps/unity/server/build-test/) is excluded by the repo's declared intent,
  // not by enumerating names here.
  let allFiles = walk(root, configRegexes);

  // Compiled-twin backstop: drop a .js/.cjs/.mjs file when a sibling .ts/.tsx source of the
  // same basename lives in the same directory — that .js is build output (a compiled twin),
  // not source, and counting it doubles importer counts and pollutes the Map. Conservative:
  // only dropped when a .ts twin actually exists, so hand-written standalone .js is kept.
  // Catches build output the .gitignore pass missed, and generalises to any build-dir name.
  {
    const tsKeys = new Set();
    for (const f of allFiles) {
      const ext = path.extname(f.rel).toLowerCase();
      if (ext === '.ts' || ext === '.tsx') {
        tsKeys.add(f.rel.slice(0, -ext.length)); // dir + basename, no extension
      }
    }
    const before = allFiles.length;
    allFiles = allFiles.filter((f) => {
      const ext = path.extname(f.rel).toLowerCase();
      if (ext === '.js' || ext === '.cjs' || ext === '.mjs') {
        return !tsKeys.has(f.rel.slice(0, -ext.length));
      }
      return true;
    });
    const dropped = before - allFiles.length;
    if (dropped) log(args, `compiled-twin backstop: dropped ${dropped} .js files shadowing .ts source`);
  }

  log(args, `scanned: ${allFiles.length} files`);

  const moduleRoots = detectModuleRoots(allFiles, config.modules);
  moduleOf = makeModuleOf(moduleRoots);
  const manifestByModule = new Map(moduleRoots.filter((r) => r.manifest).map((r) => [r.dir, r.manifest]));
  const projectsByModule = new Map(moduleRoots.filter((r) => r.projects).map((r) => [r.dir, r.projects]));
  if (moduleRoots.length) {
    const how = config.modules.depth || config.modules.patterns.length ? 'from ## Modules in codemap.config.md' : 'sub-projects found by their manifests';
    const crowded = [...projectsByModule].map(([d, ps]) => `${d} (${ps.length})`).join(', ');
    log(args, `modules: ${moduleRoots.length} nested module folders, ${how}${crowded ? `; sub-projects grouped under ${crowded}` : ''}`);
  }

  // Tree-sitter readiness: probe once. When the optional deps aren't installed this is
  // null and every AST language falls back to regex (or empty) — graceful degradation.
  const hasAstLang = allFiles.some((f) => isTreeSitterLang(LANG_BY_EXT[path.extname(f.rel).toLowerCase()] || 'other')
    || TREE_SITTER_TAG[LANG_BY_EXT[path.extname(f.rel).toLowerCase()] || 'other']);
  let treeSitterReady = false;
  if (hasAstLang) {
    treeSitterReady = (await initTreeSitter()) !== null;
    if (!treeSitterReady) {
      log(args, 'tree-sitter deps not installed — AST languages fall back to regex/empty. ' +
        'Run `npm install` in skills/update-codemap for full multi-language coverage.');
    }
  }

  const vendoredRegexes = config.vendoredPatterns.map(configGlobToRegex);
  const isVendored = (rel) => vendoredRegexes.some((re) => re.test(rel));

  const groups = new Map();
  const moduleImports = new Map();
  const fileCalls = new Map(); // rel → [{caller, callee}] (call edges)
  const fileCallSeq = new Map(); // rel → [{caller, callees: [...source order, deduped NOT]}] (call SEQUENCE, for sequence diagrams)
  const fileCallResolution = new Map(); // rel → [{caller, callee, receiver, qualified, confidence}] (type-resolved call edges)
  const fileDefines = new Map(); // rel → function/method names defined in that file (call-graph resolution)
  const fileRefs = new Map(); // rel → raw doc/config path references (## References)
  // Collected during the scan; feeds the C# namespace→file index that resolveImport
  // consults for `using` directives. Built after the loop so heads are read once.
  const namespaceByRel = new Map();

  // Per-file extraction cache (per-file extraction cache). Load the prior cache, validate each
  // file by stamp, reuse the cached parse on a hit. `nextCache` accumulates this run's
  // entries (hits carried forward, misses re-extracted) and is written at the end.
  const cachePath = path.join(root, '.claude', 'codemap.cache.json');
  const prevCache = args.noCache ? {} : loadExtractCache(cachePath);
  const nextCache = {};
  let cacheHits = 0, cacheMisses = 0;

  // Cache misses that need the AST, parsed in parallel up front when there are many.
  const astJobs = [];
  if (treeSitterReady) {
    for (const f of allFiles) {
      const tag = TREE_SITTER_TAG[LANG_BY_EXT[path.extname(f.rel).toLowerCase()] || 'other'];
      if (!tag || isVendored(f.rel)) continue;
      const stamp = fileStamp(f.abs);
      const cached = !args.noCache && stamp ? prevCache[f.rel] : null;
      if (cached && cached.size === stamp.size && cached.mtime === stamp.mtime) continue;
      astJobs.push({ rel: f.rel, abs: f.abs, lang: tag });
    }
  }
  const preParsed = await extractInParallel(astJobs);

  for (const f of allFiles) {
    const ext = path.extname(f.rel).toLowerCase();
    const lang = LANG_BY_EXT[ext] || 'other';
    const stamp = fileStamp(f.abs);

    // Cache hit: file unchanged since last run → reuse the stored extraction, skip the
    // read + (expensive) tree-sitter/regex parse entirely. A `generated` file is cached
    // as a skip sentinel so we don't re-read it either.
    const cached = !args.noCache && stamp ? prevCache[f.rel] : null;
    if (cached && cached.size === stamp.size && cached.mtime === stamp.mtime) {
      cacheHits++;
      nextCache[f.rel] = cached;
      if (cached.generated) continue;
      const top = moduleOf(f.rel);
      if (!groups.has(top)) groups.set(top, []);
      groups.get(top).push({ rel: f.rel, purpose: cached.purpose, exports: cached.exports, classes: cached.classes, vendored: cached.vendored,
        size: cached.size, lines: cached.lines, hash: cached.hash, symbols: cached.symbols || [] });
      if (cached.refs && cached.refs.length) fileRefs.set(f.rel, cached.refs);
      if (cached.imports && cached.imports.length) moduleImports.set(f.rel, cached.imports);
      if (cached.namespace) namespaceByRel.set(f.rel, cached.namespace);
      if (cached.calls && cached.calls.length) fileCalls.set(f.rel, cached.calls);
      if (cached.callSeq && cached.callSeq.length) fileCallSeq.set(f.rel, cached.callSeq);
      if (cached.callResolution && cached.callResolution.length) fileCallResolution.set(f.rel, cached.callResolution);
      if (cached.defines && cached.defines.length) fileDefines.set(f.rel, cached.defines);
      continue;
    }
    cacheMisses++;

    const head = readHead(f.abs, READ_CAP_LINES);
    if (isGenerated(head.lines)) {
      if (stamp) nextCache[f.rel] = { ...stamp, generated: true };
      continue;
    }

    const vendored = isVendored(f.rel);

    let exports = [];
    let classes = [];
    let text = head.text;
    let astImports = null; // non-null when the tree-sitter engine supplied imports
    let calls = [];         // call edges; AST-only, empty for regex langs
    let callSeq = [];        // ordered per-caller call sequence (AST-only); raw material for sequence diagrams
    let callResolution = []; // type-resolved call edges (TS/C# only); empty otherwise
    let defines = [];        // function/method names defined in this file (project-symbol signal)
    let astSymbols = [];     // outline from the AST: classes and functions with line ranges

    const tsTag = TREE_SITTER_TAG[lang];
    if (!vendored && tsTag && treeSitterReady) {
      // AST languages get the FULL file — declarations past the head-cap matter.
      const full = readFull(f.abs);
      const ast = preParsed.has(f.rel) ? preParsed.get(f.rel) : await extractWithTreeSitter(full, tsTag);
      if (ast) {
        text = full;
        exports = ast.exports;
        classes = ast.classes;
        astImports = ast.imports;
        calls = ast.calls || [];
        callSeq = ast.callSeq || [];
        callResolution = ast.callResolution || [];
        defines = ast.defines || [];
        astSymbols = ast.symbols || [];
      }
    }

    // Regex extraction: primary for ts/csharp, and the fallback for cpp when the AST
    // engine was unavailable or returned null (classes still empty here).
    if (!vendored && classes.length === 0 && exports.length === 0 &&
        (lang === 'ts' || lang === 'tsx' || lang === 'csharp' || lang === 'cpp-header')) {
      if (head.totalLines > READ_CAP_LINES && text === head.text) {
        const extended = readHead(f.abs, READ_CAP_EXTENDED);
        text = extended.text;
      }
      if (lang === 'ts' || lang === 'tsx') { exports = extractExportsTs(text); classes = extractClassesTs(text); }
      else if (lang === 'csharp') { exports = extractExportsCSharp(text); classes = extractClassesCSharp(text); }
      else if (lang === 'cpp-header') { exports = extractExportsCppHeader(text); classes = extractClassesCpp(text); }
    }

    const purpose = vendored ? '<vendored>' : (derivePurpose(head.lines, f.rel, head.text) ?? fallbackPurpose(f.rel, exports));
    const top = moduleOf(f.rel);
    if (!groups.has(top)) groups.set(top, []);
    const lines = head.text === '' ? 0 : head.totalLines - (head.text.endsWith('\n') ? 1 : 0);
    const hash = crypto.createHash('sha1').update(head.text).digest('hex').slice(0, 16);
    const symbols = vendored ? [] : buildSymbols(astSymbols, exports, classes, head.text);
    const refs = vendored ? [] : extractRefs(head.text, f.rel);
    if (refs.length) fileRefs.set(f.rel, refs);
    groups.get(top).push({ rel: f.rel, purpose, exports, classes, vendored, size: stamp ? stamp.size : head.text.length, lines, hash, symbols });

    let imports = [];
    if (!vendored) {
      // Prefer AST-extracted imports; else regex. (cpp-impl has no AST classes but its
      // includes still come through the engine when ready.)
      imports = astImports !== null ? astImports : extractImports(text, lang);
      if (imports.length) moduleImports.set(f.rel, imports);
      if (calls.length) fileCalls.set(f.rel, calls);
      if (callSeq.length) fileCallSeq.set(f.rel, callSeq);
      if (callResolution.length) fileCallResolution.set(f.rel, callResolution);
      if (defines.length) fileDefines.set(f.rel, defines);
    }

    // C# namespace declaration → index entry, so `using` directives in other files
    // resolve to this file's module. Non-vendored .cs only; a file may declare a
    // namespace without exporting a class, so this is independent of `classes`.
    let namespace = '';
    if (!vendored && lang === 'csharp') {
      const nsMatch = text.match(/^\s*namespace\s+([A-Za-z_][\w.]*)\s*[;{]/m);
      if (nsMatch) { namespace = nsMatch[1]; namespaceByRel.set(f.rel, namespace); }
    }
    // PHP: `namespace Geo\Core;` → dotted `Geo.Core`, indexed so a `use Geo\Core\IShape`
    // in another file resolves to this file via the shared byNamespace resolver (PHP
    // namespaces, like C#, don't mirror directory layout).
    if (!vendored && lang === 'php') {
      const nsMatch = text.match(/^\s*namespace\s+([A-Za-z_\\][\w\\]*)\s*[;{]/m);
      if (nsMatch) { namespace = nsMatch[1].replace(/^\\+/, '').split('\\').filter(Boolean).join('.'); namespaceByRel.set(f.rel, namespace); }
    }

    // Store this run's extraction so the next regen can skip it if unchanged.
    if (stamp) nextCache[f.rel] = { ...stamp, purpose, exports, classes, vendored, imports, namespace, calls, callSeq, callResolution, defines, lines, hash, symbols, refs };
  }
  if (!args.noCache) log(args, `cache: ${cacheHits} hits, ${cacheMisses} misses`);

  const fileIndex = buildFileIndex(allFiles, namespaceByRel);
  const topLevelDirs = new Set(groups.keys());

  // Edges. Two layers:
  //   moduleEdges[from][to] = count           (weighted, for ## Dependencies)
  //   fileEdges[from] = Set<targetRel>        (for ## File deps)
  const moduleEdges = new Map();
  const fileEdges = new Map();
  // TS/JS: tsconfig `paths`/`baseUrl` and workspace package names before the generic
  // resolver, and `outDir` build output mapped back to `rootDir` source after it.
  const projectPaths = loadProjectPaths(root, allFiles);
  const toFile = (rel) => {
    const hit = rel && matchAgainstIndex(rel, fileIndex);
    return hit ? { rel: hit, mod: moduleOf(hit) } : null;
  };
  const symbolsByFile = buildSymbolsByFile(fileDefines, groups);
  const filesInDir = new Map();
  for (const f of allFiles) {
    const dir = path.posix.dirname(f.rel);
    if (!filesInDir.has(dir)) filesInDir.set(dir, []);
    filesInDir.get(dir).push(f.rel);
  }
  // The files of the package (Go import path) or namespace (C#/PHP `using`) an import
  // names, or null when it names neither.
  const packageFiles = (t, lang) => {
    if (lang === 'go') {
      const segs = t.split('/');
      for (let k = segs.length; k >= 1; k--) {
        const tail = segs.slice(segs.length - k).join('/');
        const dirs = [...filesInDir.keys()].filter((d) => d === tail || d.endsWith('/' + tail));
        if (dirs.length === 1) return filesInDir.get(dirs[0]).filter((r) => r.endsWith('.go') && !r.endsWith('_test.go'));
        if (dirs.length > 1) return null;
      }
      return null;
    }
    if ((lang === 'csharp' || lang === 'php') && fileIndex.byNamespace.has(t)) return fileIndex.byNamespace.get(t);
    return null;
  };
  const addFileEdge = (sourceRel, rel) => {
    if (rel === sourceRel) return;
    if (!fileEdges.has(sourceRel)) fileEdges.set(sourceRel, new Set());
    fileEdges.get(sourceRel).add(rel);
  };
  const addModuleEdge = (sourceMod, targetMod) => {
    if (targetMod === sourceMod) return;
    if (!moduleEdges.has(sourceMod)) moduleEdges.set(sourceMod, new Map());
    const bucket = moduleEdges.get(sourceMod);
    bucket.set(targetMod, (bucket.get(targetMod) || 0) + 1);
  };
  for (const [sourceRel, targets] of moduleImports.entries()) {
    const sourceMod = moduleOf(sourceRel);
    const lang = LANG_BY_EXT[path.extname(sourceRel).toLowerCase()];
    const isJsLike = lang === 'ts' || lang === 'tsx';
    for (const t of targets) {
      if (t.startsWith('py-from:')) {
        const rel = resolvePyFrom(t.slice('py-from:'.length), sourceRel, fileIndex.byRel);
        if (rel) { addFileEdge(sourceRel, rel); addModuleEdge(sourceMod, moduleOf(rel)); }
        continue;
      }
      // A package or namespace import depends on the files that define what this file uses.
      const pkg = packageFiles(t, lang);
      if (pkg && pkg.length > 1) {
        const used = usedNames(sourceRel, fileCalls, groups);
        const hits = pkg.filter((r) => [...(symbolsByFile.get(r) || [])].some((n) => used.has(n)));
        if (hits.length) {
          for (const r of hits) addFileEdge(sourceRel, r);
          addModuleEdge(sourceMod, moduleOf(hits[0]));
          continue;
        }
      }
      const isRelative = t.startsWith('.');
      let resolved = null;
      if (isJsLike && !isRelative) {
        for (const c of aliasCandidates(t, sourceRel, projectPaths)) if ((resolved = toFile(c))) break;
      }
      if (!resolved) resolved = resolveImport(t, sourceRel, topLevelDirs, fileIndex);
      if (isJsLike && isRelative && !(resolved && resolved.rel)) {
        const built = path.posix.normalize(path.posix.join(path.posix.dirname(sourceRel), t));
        resolved = toFile(buildToSource(built, projectPaths)) || resolved;
      }
      if (!resolved) continue;
      const targetMod = resolved.mod;
      if (!targetMod) continue;
      if (resolved.rel && resolved.rel !== sourceRel) {
        if (!fileEdges.has(sourceRel)) fileEdges.set(sourceRel, new Set());
        fileEdges.get(sourceRel).add(resolved.rel);
      }
      if (targetMod === sourceMod) continue;
      if (!moduleEdges.has(sourceMod)) moduleEdges.set(sourceMod, new Map());
      const bucket = moduleEdges.get(sourceMod);
      bucket.set(targetMod, (bucket.get(targetMod) || 0) + 1);
    }
  }

  // Doc and config references (markdown links and path spans, paths in json/yaml/toml),
  // minus any pair already joined by an import.
  const refEdges = new Map();
  for (const [sourceRel, raws] of fileRefs.entries()) {
    for (const raw of raws) {
      const target = resolveRef(raw, sourceRel, fileIndex.byRel);
      if (!target || (fileEdges.get(sourceRel) && fileEdges.get(sourceRel).has(target))) continue;
      if (!refEdges.has(sourceRel)) refEdges.set(sourceRel, new Set());
      refEdges.get(sourceRel).add(target);
    }
  }

  const entryPoints = detectEntryPoints(root, allFiles, moduleRoots,
    (rel) => (toFile(rel) || toFile(buildToSource(rel, projectPaths)) || {}).rel || null);

  const today = new Date().toISOString().slice(0, 10);

  // ----- LLM-facing prose header (Overview, Modules, Conventions, Hubs).
  // Section ordering is load-bearing: prose first, then the structured sections
  // consumed by visualise-codemap. The visualize parser keys on `## <name>/`
  // for groups and on a fixed set of named sections (Entry points, Layers,
  // Dependencies, File deps, Class graph) — anything else is benign noise.
  const inboundCounts = computeInboundCounts(fileEdges);
  const importedBy = computeModuleImportedBy(moduleEdges);
  const moduleImportance = computeModuleImportance(groups, inboundCounts);
  const readmeH1 = readReadmeH1(root);
  const pkgDesc = readPackageDescription(root);
  const domLang = dominantLanguage(groups);

  let out = `# Architecture — ${projectName}\nLast updated: ${today}\n\n`;

  // ## Overview
  const overviewParts = [];
  const ensurePeriod = (s) => /[.!?]$/.test(s.trim()) ? s.trim() : (s.trim() + '.');
  if (readmeH1) overviewParts.push(ensurePeriod(readmeH1));
  else if (pkgDesc) overviewParts.push(ensurePeriod(pkgDesc));
  else overviewParts.push(`${projectName} — codemap-derived architecture summary.`);
  if (entryPoints.length) {
    overviewParts.push(`Entry: ${entryPoints.slice(0, 2).map((e) => `\`${e.rel}\``).join(', ')}.`);
  }
  if (domLang) overviewParts.push(`Dominant language: ${domLang}.`);
  out += `## Overview\n${overviewParts.join(' ')}\n\n`;

  // ## Map — the agent's entry point: the most-depended-on hub files, ranked, so the
  // agent reads these FIRST instead of scanning the tree (hub-first ordering). Distinct
  // from `## Hubs` below (≥3 inbound, full list) — this is the top slice with purposes.
  const mapEntries = [];
  for (const [file, count] of inboundCounts.entries()) {
    let purpose = '';
    for (const items of groups.values()) {
      const hit = items.find((it) => it.rel === file);
      if (hit) { purpose = hit.purpose; break; }
    }
    mapEntries.push({ file, count, purpose });
  }
  mapEntries.sort((a, b) => b.count - a.count || a.file.localeCompare(b.file));
  const topMap = mapEntries.filter((e) => e.count > 0).slice(0, 12);
  if (topMap.length) {
    out += `## Map\nStart here — the most-depended-on files, ranked by importers:\n\n`;
    out += `| File | Importers | Role |\n|---|---|---|\n`;
    for (const e of topMap) {
      const role = (e.purpose && e.purpose !== '<vendored>') ? e.purpose.replace(/\|/g, '\\|') : '';
      out += `| \`${e.file}\` | ${e.count} | ${role} |\n`;
    }
    out += `\n`;
  }

  // ## Modules — ordered by importance (sum of inbound edges), most-depended-on first,
  // so the agent meets the load-bearing modules before the leaves (hub-first ordering).
  const sortedModuleNames = modulesByImportance(groups, moduleImportance);
  if (sortedModuleNames.length) {
    out += `## Modules\n`;
    for (const modName of sortedModuleNames) {
      const items = groups.get(modName);
      // Markdown-dominant folders (rule/doc corpora) get a name+count role and no scraped
      // purpose — see isMarkdownDominant. Code modules keep the inferred role/purpose.
      const mdDominant = isMarkdownDominant(items);
      const manifest = manifestByModule.get(modName);
      const declared = manifest ? manifestDescription(root, manifest) : '';
      const role = declared || (mdDominant ? markdownFolderRole(modName, items) : inferModuleRole(modName, items));
      const purpose = mdDominant ? '' : inferModulePurpose(items, inboundCounts);
      const entry = findModuleEntry(modName, items, entryPoints);
      const surface = publicSurfaceForModule(items, inboundCounts);
      const depsOn = moduleEdges.has(modName)
        ? [...moduleEdges.get(modName).keys()].sort()
        : [];
      const impBy = importedBy.has(modName)
        ? [...importedBy.get(modName)].sort()
        : [];
      const internals = computeInternals(modName, items, inboundCounts);

      out += `### ${modName}\n`;
      out += `**Role:** ${role}\n`;
      if (manifest) out += `**Manifest:** \`${manifest}\`\n`;
      const projects = projectsByModule.get(modName);
      if (projects) {
        const names = projects.map((d) => d.slice(modName.length));
        out += `**Projects:** ${projects.length} sub-projects: ${names.slice(0, 40).join(', ')}${names.length > 40 ? ', …' : ''}\n`;
      }
      if (purpose) out += `**Purpose:** ${purpose}\n`;
      if (entry) out += `**Entry:** \`${entry}\`\n`;
      if (surface.length) out += `**Public surface:** ${surface.map((s) => `\`${s}\``).join(', ')}\n`;
      if (depsOn.length) out += `**Depends on:** ${depsOn.join(', ')}\n`;
      if (impBy.length) out += `**Imported by:** ${impBy.join(', ')}\n`;
      if (internals.length) {
        out += `**Internals:**\n`;
        for (const line of internals) out += `- ${line}\n`;
      }
      out += `\n`;
    }
  }

  // ## Conventions detected — only fire for ≥3-instance explicit markers.
  const conventions = detectConventions(groups);
  if (conventions.length) {
    out += `## Conventions detected\n`;
    for (const c of conventions) {
      out += `- ${c.name}: ${c.count} instances — ${c.detail}\n`;
    }
    out += `\n`;
  }

  // ## Hubs — files with ≥3 inbound file-edges, ranked by importer count.
  const hubEntries = [];
  for (const [file, count] of inboundCounts.entries()) {
    if (count < 3) continue;
    // Find purpose by scanning groups.
    let purpose = '';
    for (const items of groups.values()) {
      const hit = items.find((it) => it.rel === file);
      if (hit) { purpose = hit.purpose; break; }
    }
    hubEntries.push({ file, count, purpose });
  }
  hubEntries.sort((a, b) => b.count - a.count || a.file.localeCompare(b.file));
  if (hubEntries.length) {
    out += `## Hubs\n`;
    for (const h of hubEntries) {
      const tail = h.purpose ? `, role: ${h.purpose}` : '';
      out += `- \`${h.file}\` — ${h.count} importers${tail}\n`;
    }
    out += `\n`;
  }

  // ## Symbol index — "where is X" lookup: exported/public symbol → defining file
  // (symbol index). Ranked by the file's inbound count so the most-used symbols
  // lead and survive --map-tokens truncation. The agent greps this section instead of
  // the repo. Capped at 200 here; --map-tokens may trim further.
  const symbolIndex = buildSymbolIndex(groups, inboundCounts);
  if (symbolIndex.length) {
    out += `## Symbol index\n`;
    for (const s of symbolIndex.slice(0, 200)) {
      out += `- \`${s.name}\` → \`${s.file}\`\n`;
    }
    out += `\n`;
  }

  // ## Recent activity — where work is happening now: the files with the most commits in
  // the last ACTIVITY_DAYS (git log is newest first, so `last` is the latest change).
  const activity = gitActivity(root);
  const indexed = new Set(allFiles.map((f) => f.rel));
  const active = [...activity.entries()].filter(([rel]) => indexed.has(rel))
    .sort((a, b) => b[1].commits - a[1].commits || b[1].last.localeCompare(a[1].last) || a[0].localeCompare(b[0]))
    .slice(0, ACTIVITY_TOP);
  if (active.length) {
    out += `## Recent activity\nFiles changed most in the last ${ACTIVITY_DAYS} days:\n`;
    for (const [rel, a] of active) out += `- \`${rel}\` — ${a.commits} commit${a.commits === 1 ? '' : 's'}, last ${a.last}\n`;
    out += `\n`;
  }

  if (entryPoints.length) {
    out += `## Entry points\n`;
    for (const e of entryPoints) out += `- \`${e.rel}\` — ${e.role}\n`;
    out += `\n`;
  }
  if (config.layers.length) {
    out += `## Layers\n`;
    for (const l of config.layers) out += `- ${l.name}: ${l.modules.join(', ')}\n`;
    out += `\n`;
  }
  if (moduleEdges.size) {
    out += `## Dependencies\n`;
    const sortedSources = [...moduleEdges.keys()].sort();
    for (const s of sortedSources) {
      // Sort by weight desc, then name asc, and render `target (N)`.
      const entries = [...moduleEdges.get(s).entries()]
        .sort((a, b) => (b[1] - a[1]) || a[0].localeCompare(b[0]));
      const rendered = entries.map(([t, w]) => `${t} (${w})`).join(', ');
      out += `- ${s} → ${rendered}\n`;
    }
    out += `\n`;
  }
  if (fileEdges.size) {
    out += `## File deps\n`;
    const sortedSources = [...fileEdges.keys()].sort();
    for (const s of sortedSources) {
      const targets = [...fileEdges.get(s)].sort();
      out += `- \`${s}\` → ${targets.map((t) => `\`${t}\``).join(', ')}\n`;
    }
    out += `\n`;
  }

  // ## References — doc and config files pointing at other files. Not imports: they
  // never count as importers and affected-tests ignores them.
  if (refEdges.size) {
    out += `## References\n`;
    for (const s of [...refEdges.keys()].sort()) {
      out += `- \`${s}\` → ${[...refEdges.get(s)].sort().map((t) => `\`${t}\``).join(', ')}\n`;
    }
    out += `\n`;
  }

  // Phase 1c: ## Class graph — class-level data for UML rendering and convention detection.
  // Block-per-class shape: parser keys off "- class:" / "- interface:" / "- struct:" / "- record:" / "- enum:".
  // Sub-lines (indented 2 spaces) carry attributes; each starts with a stable keyword followed by ":".
  const allClassEntries = [];
  for (const [g, items] of groups.entries()) {
    for (const it of items) {
      if (!it.classes || !it.classes.length) continue;
      for (const c of it.classes) {
        allClassEntries.push({ file: it.rel, module: g, ...c });
      }
    }
  }

  // Cross-file confirmation for type resolution. The per-file resolvers (TS/C#) emit `unconfirmed` resolutions
  // when a receiver's TYPE is known (annotation / `new`) but its class is declared in ANOTHER
  // file (imported). Confirm those against the project Type→methods registry built from every
  // file's extracted class methods: keep the qualified edge only when the method actually exists
  // on that type; drop it otherwise (degrade to the syntactic edge — never a false resolved edge,
  // honest-degrade per silent-catch-masks-structural-bug). Same-file resolutions are already
  // confirmed and pass through untouched.
  const typeMethodRegistry = new Map(); // typeName → Set<method>
  for (const c of allClassEntries) {
    if (!c.name || !c.methods || !c.methods.length) continue;
    if (!typeMethodRegistry.has(c.name)) typeMethodRegistry.set(c.name, new Set());
    const set = typeMethodRegistry.get(c.name);
    for (const m of c.methods) set.add(m);
  }
  for (const [rel, resolutions] of fileCallResolution.entries()) {
    const confirmed = [];
    for (const r of resolutions) {
      if (!r.unconfirmed) { confirmed.push(r); continue; } // same-file, already confirmed
      const methods = typeMethodRegistry.get(r.type);
      if (methods && methods.has(r.callee)) {
        // Cross-file confirmed: the imported type really declares this method.
        confirmed.push({ caller: r.caller, callee: r.callee, receiver: r.receiver, qualified: r.qualified, confidence: r.confidence });
      }
      // else: unconfirmed against the registry → drop (the syntactic edge stands).
    }
    if (confirmed.length) fileCallResolution.set(rel, confirmed);
    else fileCallResolution.delete(rel);
  }

  // Apply type resolution: build a lookup (file, caller, callee) → { qualified, confidence } for resolutions
  // at/above the confidence floor. The call-graph emit consults this to render the resolved
  // `Type.method` in place of the bare callee; below-floor or absent → the syntactic edge stands.
  // A single syntactic edge (file, caller, callee) can resolve to MULTIPLE qualified targets
  // when the same method name is called on different typed receivers in one function
  // (`r.get()` → Repo.get AND `c.get()` → Cache.get). The syntactic graph collapsed them by
  // name; resolution un-collapses them. So map to a SET of qualified names, and the emit
  // expands one syntactic edge into one line per resolved target.
  const resolvedEdgeMap = new Map(); // `${file} ${caller} ${callee}` → Set<qualified>
  for (const [rel, resolutions] of fileCallResolution.entries()) {
    for (const r of resolutions) {
      if (r.confidence < CALL_RESOLUTION_FLOOR) continue;
      const key = `${rel} ${r.caller} ${r.callee}`;
      if (!resolvedEdgeMap.has(key)) resolvedEdgeMap.set(key, new Set());
      resolvedEdgeMap.get(key).add(r.qualified);
    }
  }
  if (allClassEntries.length) {
    out += `## Class graph\n`;
    // Most-imported files first, so the size cap drops the least-used classes.
    const sorted = allClassEntries.sort((a, b) => (inboundCounts.get(b.file) || 0) - (inboundCounts.get(a.file) || 0) ||
      a.file.localeCompare(b.file) || a.name.localeCompare(b.name));
    for (const c of sorted) {
      out += `- ${c.kind}: \`${c.name}\` in \`${c.file}\`\n`;
      if (c.namespace) out += `  namespace: ${c.namespace}\n`;
      if (c.extends.length) out += `  extends: ${c.extends.join(' ; ')}\n`;
      if (c.implements.length) out += `  implements: ${c.implements.join(' ; ')}\n`;
      if (c.attributes.length) out += `  attributes: ${c.attributes.join(' ; ')}\n`;
      if (c.fields.length) {
        const renderedFields = c.fields.map((f) => `${f.name}: ${f.type}`).join(' ; ');
        out += `  fields: ${renderedFields}\n`;
      }
    }
    out += `\n`;
  }

  // Which files a call in `rel` can reach: itself, the files it imports, its package or
  // namespace for languages that see those without an import, and the header/impl twin of
  // each. A callee counts as project code only when one of these files defines it, so a
  // builtin `split()` no longer matches some unrelated file's `split` function.
  const filesByDir = new Map();
  const filesByStem = new Map();
  for (const f of allFiles) {
    const dir = path.posix.dirname(f.rel);
    if (!filesByDir.has(dir)) filesByDir.set(dir, []);
    filesByDir.get(dir).push(f.rel);
    const stem = f.rel.replace(/\.[^./]+$/, '');
    if (!filesByStem.has(stem)) filesByStem.set(stem, []);
    filesByStem.get(stem).push(f.rel);
  }
  const scopeCache = new Map();
  const callScope = (rel) => {
    if (scopeCache.has(rel)) return scopeCache.get(rel);
    const files = new Set([rel, ...(fileEdges.get(rel) || [])]);
    if (PACKAGE_SCOPED_LANGS.has(LANG_BY_EXT[path.extname(rel).toLowerCase()])) {
      for (const f of filesByDir.get(path.posix.dirname(rel)) || []) files.add(f);
    }
    for (const ns of [namespaceByRel.get(rel), ...(moduleImports.get(rel) || [])]) {
      for (const f of (ns && fileIndex.byNamespace.get(ns)) || []) files.add(f);
    }
    for (const f of [...files]) for (const twin of filesByStem.get(f.replace(/\.[^./]+$/, '')) || []) files.add(twin);
    const names = new Set();
    for (const f of files) for (const n of symbolsByFile.get(f) || []) names.add(n);
    scopeCache.set(rel, names);
    return names;
  };

  // ## Call graph — per-module subgraphs of caller→callee edges, mirroring the per-module
  // ## File deps layout. Only calls that resolve to a symbol defined in the call's scope
  // (see callScope) are listed; calls to builtins, stdlib and packages are left out and
  // counted in the header. TypeScript and C# edges render as `Type.method` when the
  // receiver type resolved. Ranked by callee in-degree, capped per module with a `(+K more)`
  // overflow line. Parser leader: per-module `### <mod>` then
  // `- \`file::caller\` → \`callee\`` lines (visualizer keys on the arrow).
  const jsonCalls = []; // every in-scope call edge, uncapped, for codemap.json
  const jsonCallSeq = []; // every in-scope call sequence, uncapped, for codemap.json
  if (fileCalls.size) {
    const byModule = new Map(); // mod → [{ file, caller, callee, qualified }]
    let externalCalls = 0;
    for (const [rel, edges] of fileCalls.entries()) {
      const mod = moduleOf(rel);
      const scope = callScope(rel);
      for (const e of edges) {
        // Attach the type-resolved qualified callee(s) (Type.method) when the resolver
        // produced them above the floor; one syntactic edge may expand into several resolved
        // ones (same method name, different typed receivers). Else the edge stays syntactic.
        const res = resolvedEdgeMap.get(`${rel} ${e.caller} ${e.callee}`);
        if (!(res && res.size) && !scope.has(e.callee)) { externalCalls++; continue; }
        if (!byModule.has(mod)) byModule.set(mod, []);
        const bucket = byModule.get(mod);
        const base = { file: rel, caller: e.caller, callee: e.callee };
        if (res && res.size) {
          for (const q of res) {
            bucket.push({ ...base, qualified: q });
            jsonCalls.push({ file: rel, caller: e.caller, callee: q });
          }
        } else {
          bucket.push({ ...base, qualified: null });
          jsonCalls.push({ file: rel, caller: e.caller, callee: e.callee });
        }
      }
    }
    const anyTypeResolved = [...byModule.values()].some((es) => es.some((e) => e.qualified));
    out += `## Call graph\n`;
    out += `_Syntactic / name-matched: caller → callee by bare name, kept only when the callee is ` +
      `defined in the calling file, a file it imports, or (for package-scoped languages) its package or namespace. ` +
      `${externalCalls} calls to builtins, packages or unresolved names are left out. ` +
      `Per-module capped at ${CALL_EDGE_CAP_PER_MODULE} edges; overflow summarized._\n`;
    if (anyTypeResolved) {
      out += `_**Type-resolved:** TypeScript and C# call edges shown as \`Type.method\` are ` +
        `receiver-type-resolved (the receiver's type was resolved via declarations/imports, confidence ≥ ${CALL_RESOLUTION_FLOOR}). ` +
        `Bare-name edges are syntactic fallback. Other languages remain syntactic-only._\n`;
    }
    for (const mod of [...byModule.keys()].sort()) {
      const edges = byModule.get(mod);
      // Rank by callee in-degree so the genuine hubs survive the cap.
      const calleeDegree = new Map();
      for (const e of edges) calleeDegree.set(e.callee, (calleeDegree.get(e.callee) || 0) + 1);
      edges.sort((a, b) =>
        (calleeDegree.get(b.callee) - calleeDegree.get(a.callee)) ||
        a.file.localeCompare(b.file) || a.caller.localeCompare(b.caller) || a.callee.localeCompare(b.callee));
      const shown = edges.slice(0, CALL_EDGE_CAP_PER_MODULE);
      const overflow = edges.length - shown.length;
      out += `### ${mod}\n`;
      for (const e of shown) {
        const base = path.posix.basename(e.file);
        // Render the resolved Type.method when present, else the syntactic bare callee.
        const target = e.qualified || e.callee;
        out += `- \`${base}::${e.caller}\` → \`${target}\`\n`;
      }
      if (overflow > 0) out += `- (+${overflow} more)\n`;
    }
    out += `\n`;
  }

  // ## Call sequence — ordered per-caller call chains (the raw material for sequence
  // diagrams). Unlike ## Call graph (a deduped name-matched edge set), this preserves the
  // ORDER calls appear in the source and keeps duplicates. It is STATIC call-structure order,
  // NOT runtime flow — no conditionals, loops, or await timing — and the visualizer renders
  // it as sequence diagrams with that caveat. Capped: top-fan-out callers per module, callees
  // per chain; overflow summarized.
  if (fileCallSeq.size) {
    const seqByModule = new Map(); // mod → [{ file, caller, callees }]
    for (const [rel, seqs] of fileCallSeq.entries()) {
      const mod = moduleOf(rel);
      if (!seqByModule.has(mod)) seqByModule.set(mod, []);
      const bucket = seqByModule.get(mod);
      for (const s of seqs) {
        if (!s || !s.caller || !s.callees) continue;
        const scope = callScope(rel);
        const callees = s.callees.filter((c) => scope.has(c));
        if (!callees.length) continue;
        bucket.push({ file: rel, caller: s.caller, callees });
        jsonCallSeq.push({ file: rel, caller: s.caller, callees });
      }
    }
    if ([...seqByModule.values()].some((b) => b.length)) {
      out += `## Call sequence\n`;
      out += `_Static call-structure order: the order calls appear in each function's source — NOT runtime flow ` +
        `(no conditionals, loops, or await timing). Duplicates are kept. Syntactic / name-matched, like the call graph. ` +
        `The visualizer renders these as sequence diagrams with the same caveat. Top ${CALL_SEQ_CALLERS_PER_MODULE} fan-out ` +
        `callers per module, ${CALL_SEQ_CALLEES_PER_CHAIN} callees per chain; overflow summarized._\n`;
      for (const mod of [...seqByModule.keys()].sort()) {
        const chains = seqByModule.get(mod).filter((c) => c.callees.length);
        if (!chains.length) continue;
        // Rank callers by fan-out (chain length) so the most illustrative chains survive the cap.
        chains.sort((a, b) => b.callees.length - a.callees.length ||
          a.file.localeCompare(b.file) || a.caller.localeCompare(b.caller));
        const shownChains = chains.slice(0, CALL_SEQ_CALLERS_PER_MODULE);
        const chainOverflow = chains.length - shownChains.length;
        out += `### ${mod}\n`;
        for (const c of shownChains) {
          const base = path.posix.basename(c.file);
          const shownCallees = c.callees.slice(0, CALL_SEQ_CALLEES_PER_CHAIN);
          const calleeOverflow = c.callees.length - shownCallees.length;
          const seq = shownCallees.map((x) => `\`${x}\``).join(' → ') + (calleeOverflow > 0 ? ` → (+${calleeOverflow} more)` : '');
          out += `- \`${base}::${c.caller}\`: ${seq}\n`;
        }
        if (chainOverflow > 0) out += `- (+${chainOverflow} more callers)\n`;
      }
      out += `\n`;
    }
  }

  const sortedGroups = [...groups.keys()].sort();
  for (const g of sortedGroups) {
    out += `## ${g}\n`;
    const items = groups.get(g).sort((a, b) => a.rel.localeCompare(b.rel));
    for (const it of items) {
      out += `- \`${it.rel}\` — ${it.purpose}\n`;
      if (it.exports.length) {
        // Separator is ` ; ` (not `, `) because TS/C# signatures contain commas
        // inside parameter lists, generics, and tuple types. Visualize splits on the same token.
        out += `  exports: ${it.exports.map((e) => e.name).join(' ; ')}\n`;
      }
    }
    out += `\n`;
  }

  // codemap.json: everything above, uncapped, plus per-file outline, tests and git data.
  const json = buildCodemapJson({ projectName, today, groups, sortedGroups, fileEdges, refEdges, moduleEdges, manifestByModule, projectsByModule, allClassEntries, jsonCalls, jsonCallSeq, activity, entryPoints });

  // --map-tokens budget (document-size budget, default DEFAULT_MAP_TOKENS). Trims the
  // least-valuable sections first (see TRIM_ORDER) and logs what was dropped — no silent
  // caps. codemap.json keeps everything.
  if (args.mapTokens && estimateTokens(out) > args.mapTokens) {
    out = truncateToBudget(out, args.mapTokens, args, log, inboundCounts, (h) => groups.has(h));
  }

  const codemapPath = path.join(root, '.claude', 'codemap.md');
  const dirtyPath = path.join(root, '.claude', 'codemap.dirty');
  let dirtyClearedFrom = null;
  if (fs.existsSync(dirtyPath)) {
    try { dirtyClearedFrom = fs.readFileSync(dirtyPath, 'utf8').trim(); } catch {}
  }

  const jsonPath = path.join(root, '.claude', 'codemap.json');
  if (args.dryRun) {
    log(args, '--- dry-run output ---');
    process.stdout.write(out);
    log(args, '--- end ---');
    return;
  }

  fs.mkdirSync(path.dirname(codemapPath), { recursive: true });
  const prev = loadPreviousCodemap(codemapPath);
  writeIfChanged(jsonPath, JSON.stringify(json) + '\n');
  const isUnchanged = !writeIfChanged(codemapPath, out);
  // Persist the extraction cache (per-file extraction cache) only on a real write — dry-run
  // returns above, so its cache never diverges from the on-disk map. --no-cache skips.
  if (!args.noCache) saveExtractCache(cachePath, nextCache);
  if (dirtyClearedFrom !== null) {
    try { fs.unlinkSync(dirtyPath); } catch {}
  }

  // The last run's files are the extraction cache's keys (generated files are cached as skips).
  const prevFiles = Object.entries(prevCache).filter(([, e]) => !e.generated).map(([rel]) => rel);
  const diff = diffSummary(prev, prevFiles.length ? new Set(prevFiles) : null, json);
  if (diff.initial) {
    const exported = [...groups.values()].flat().filter((it) => it.exports.length).length;
    log(args, `initial scan: ${allFiles.length} files, ${exported} with exports across ${sortedGroups.length} modules`);
  } else {
    log(args, `+ ${diff.added} files added`);
    log(args, `- ${diff.removed} files removed`);
  }
  if (config.skipPatterns.length) log(args, `config applied: ${config.skipPatterns.length} skip patterns from .claude/codemap.config.md`);
  if (config.warnings.length) {
    log(args, `warnings (malformed config lines, ignored):`);
    for (const w of config.warnings) log(args, `  - line ${w.line}: ${w.text}`);
  }
  if (dirtyClearedFrom !== null) log(args, `dirty sentinel cleared (last marked: ${dirtyClearedFrom})`);
  log(args, isUnchanged ? `unchanged ${path.relative(root, codemapPath)}` : `wrote ${path.relative(root, codemapPath)}`);
}

main().catch((err) => { console.error(err); process.exit(1); });
