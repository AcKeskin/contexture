// ----- Per-file extraction cache (per-file extraction cache) -----
// Stores the parse result for each file keyed by rel path, validated by mtimeMs+size,
// so a regen re-parses only the files that actually changed (the tree-sitter pass is
// the expensive part). Cache lives at .claude/codemap.cache.json (gitignored alongside
// codemap.md). A bumped CACHE_VERSION or a missing/corrupt file → cold rebuild, never a
// stale read. The cache is advisory: a miss just means "re-extract", so it can never
// produce a wrong map, only a slower one.
// Bumped on cached-entry schema changes (v2 added `calls`; v3 added `defines`; v4 added
// `callSeq`; v5 added `callResolution`; v7 re-derives file roles; v8 re-derives purposes; v9 adds `lines`, `hash`, `symbols`; v10 adds `refs`) — an older entry lacks the field, so the bump forces a
// one-time cold rebuild rather than a partial read.
const CACHE_VERSION = 11;

function loadExtractCache(cachePath) {
  try {
    const j = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
    if (j && j.version === CACHE_VERSION && j.files && typeof j.files === 'object') return j.files;
  } catch {}
  return {};
}

function saveExtractCache(cachePath, files) {
  try {
    fs.mkdirSync(path.dirname(cachePath), { recursive: true });
    fs.writeFileSync(cachePath, JSON.stringify({ version: CACHE_VERSION, files }, null, 0));
  } catch {}
}

// Validator for a cache entry — file unchanged iff size and mtime match. mtimeMs is
// float; round to ms to avoid FS-precision drift across platforms.
function fileStamp(abs) {
  try {
    const st = fs.statSync(abs);
    return { size: st.size, mtime: Math.floor(st.mtimeMs) };
  } catch {
    return null;
  }
}

// File bullets of the per-module `## <dir>/` groups only (other sections list files too).
function groupFiles(md) {
  const files = new Set();
  let inGroup = false;
  for (const line of md.split(/\r?\n/)) {
    if (line.startsWith('## ')) { inGroup = line.trimEnd().endsWith('/'); continue; }
    const m = inGroup && line.match(/^-\s+`([^`]+)`/);
    if (m) files.add(m[1]);
  }
  return files;
}

// Files added and removed since the last run. `cachedFiles` (the last run's extraction cache
// keys) is preferred over the markdown, whose listings the size cap may thin.
function diffSummary(prev, cachedFiles, curJson) {
  if (!prev) return { initial: true };
  const prevFiles = cachedFiles || groupFiles(prev);
  const curFiles = new Set(Object.keys(curJson.files));
  let added = 0, removed = 0;
  for (const f of curFiles) if (!prevFiles.has(f)) added++;
  for (const f of prevFiles) if (!curFiles.has(f)) removed++;
  return { added, removed };
}

// ----- LLM-facing prose section helpers -----
// These build the # Architecture header (Overview, Modules, Conventions, Hubs)
// that ships above the structured sections consumed by visualise-codemap.

function readmeProse(line) {
  return line
    .replace(/\[!\[[^\]]*\]\([^)]*\)\]\([^)]*\)/g, '') // linked badge
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '') // image
    .replace(/<[^>]+>/g, '') // HTML tag
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1') // link -> text
    .trim();
}

function readReadmeH1(root) {
  try {
    const readme = path.join(root, 'README.md');
    if (!fs.existsSync(readme)) return '';
    const text = fs.readFileSync(readme, 'utf8');
    const lines = text.split(/\r?\n/);
    const h1Index = lines.findIndex((l) => /^#\s+/.test(l));
    if (h1Index < 0) return '';
    // First prose paragraph after H1. Badge rows, images and HTML carry no
    // meaning for an agent, so they are dropped and links keep their text.
    const para = [];
    for (let i = h1Index + 1; i < Math.min(lines.length, h1Index + 30); i++) {
      const l = readmeProse(lines[i]);
      if (!l) { if (para.length) break; else continue; }
      if (/^#/.test(l)) break;
      para.push(l);
    }
    return para.join(' ').trim();
  } catch { return ''; }
}

function readPackageDescription(root) {
  try {
    const pkg = path.join(root, 'package.json');
    if (fs.existsSync(pkg)) {
      const j = JSON.parse(fs.readFileSync(pkg, 'utf8'));
      if (j.description) return String(j.description).trim();
    }
  } catch {}
  // Walk one level deep for a nested package.json description (e.g. server/package.json).
  try {
    const entries = fs.readdirSync(root, { withFileTypes: true });
    for (const ent of entries) {
      if (!ent.isDirectory() || SKIP_DIRS.has(ent.name)) continue;
      const p = path.join(root, ent.name, 'package.json');
      if (fs.existsSync(p)) {
        try {
          const j = JSON.parse(fs.readFileSync(p, 'utf8'));
          if (j.description) return String(j.description).trim();
        } catch {}
      }
    }
  } catch {}
  return '';
}

const JS_EXTS = new Set(['.js', '.mjs', '.cjs', '.jsx']);

function dominantLanguage(groups) {
  const counts = new Map();
  for (const items of groups.values()) {
    for (const it of items) {
      const ext = path.extname(it.rel).toLowerCase();
      if (!LANG_BY_EXT[ext]) continue;
      // LANG_BY_EXT names the parser grammar (.js parses as ts); report the source language.
      const lang = JS_EXTS.has(ext) ? 'js' : LANG_BY_EXT[ext];
      counts.set(lang, (counts.get(lang) || 0) + 1);
    }
  }
  const sorted = [...counts.entries()].sort((a, b) => b[1] - a[1]);
  return sorted.length ? sorted[0][0] : '';
}

