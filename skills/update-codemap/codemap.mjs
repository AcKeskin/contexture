// ----- Class graph extraction (phase 1a/1b) -----
// Returns [{ name, kind, extends, implements, fields, namespace, attributes }]
// Used by `## Class graph` consumers (visualise-codemap UML + update-codemap convention detector).

function extractClassesTs(text) {
  const out = [];
  // Match `export? abstract? class|interface Name<T> extends Base implements I, J { ... }` up to the opening brace.
  const re = /\b(?:export\s+(?:default\s+)?)?(?:abstract\s+)?(class|interface)\s+([A-Za-z_$][\w$]*)(?:\s*<[^>]*>)?\s*((?:extends\s+[A-Za-z_$][\w$.<>,\s]*?)?)\s*((?:implements\s+[A-Za-z_$][\w$.<>,\s]*?)?)\s*\{/gm;
  let m;
  while ((m = re.exec(text)) !== null) {
    // Reject matches inside a string / template literal. Cheap heuristic:
    // if the line containing the match has a backtick or quote before `class` / `interface`
    // and not closed before the keyword, skip.
    const lineStart = text.lastIndexOf('\n', m.index) + 1;
    const lineHead = text.slice(lineStart, m.index);
    if (isInsideStringOrTemplate(lineHead)) continue;

    const kind = m[1];
    const name = m[2];
    const ext = m[3].replace(/^extends\s+/, '').trim();
    const impl = m[4].replace(/^implements\s+/, '').trim();
    const extendsList = ext ? splitTypeList(ext) : [];
    const implementsList = impl ? splitTypeList(impl) : [];

    // Public class fields — `public foo: Bar;` / `readonly foo: Bar`. TS exposes via public/readonly.
    const bodyStart = m.index + m[0].length;
    const body = sliceBalanced(text, bodyStart - 1);
    const fieldRe = /^\s*(?:public\s+|readonly\s+)+([A-Za-z_$][\w$]*)\s*[?!]?\s*:\s*([A-Za-z_$][\w$.<>,\s|&\[\]]*?)\s*[;=]/gm;
    const fields = [];
    let fm;
    while ((fm = fieldRe.exec(body)) !== null) {
      fields.push({ name: fm[1], type: normalizeTypeRef(fm[2]) });
    }

    out.push({ name, kind, extends: extendsList, implements: implementsList, fields, namespace: '', attributes: [] });
  }
  return out;
}

// Naïve detector: an odd number of unescaped backticks/quotes before the position
// implies the position is inside a string. Good enough to suppress class-keyword
// matches inside template literals.
function isInsideStringOrTemplate(prefix) {
  let inBacktick = false, inSingle = false, inDouble = false;
  for (let i = 0; i < prefix.length; i++) {
    const c = prefix[i];
    if (prefix[i - 1] === '\\') continue;
    if (!inSingle && !inDouble && c === '`') inBacktick = !inBacktick;
    else if (!inBacktick && !inDouble && c === "'") inSingle = !inSingle;
    else if (!inBacktick && !inSingle && c === '"') inDouble = !inDouble;
  }
  return inBacktick || inSingle || inDouble;
}

function extractClassesCSharp(text) {
  const out = [];
  // Capture file-scoped or block namespace.
  const nsMatch = text.match(/^\s*namespace\s+([A-Za-z_][\w.]*)\s*[;{]/m);
  const namespace = nsMatch ? nsMatch[1] : '';

  // Match `[Attr] public abstract? class|struct|interface|record Name<T> : Base, I, J { ... }`
  const re = /((?:^[ \t]*\[[^\]]+\][ \t]*\r?\n)*)[ \t]*(?:public\s+|internal\s+)?(?:static\s+|readonly\s+|sealed\s+|abstract\s+|partial\s+)*(class|struct|interface|enum|record)\s+([A-Za-z_]\w*)(?:\s*<[^>]*>)?\s*(?::\s*([^\{]+?))?\s*(?:where\s+[^{]+)?\s*\{/gm;
  let m;
  while ((m = re.exec(text)) !== null) {
    const attrBlock = m[1] || '';
    const kind = m[2];
    const name = m[3];
    const inheritList = m[4] ? splitTypeList(m[4]) : [];
    // C# convention: first entry is base class if it doesn't start with `I[A-Z]`; rest are interfaces.
    // It's not airtight (e.g. ICustom is allowed as base), but it's the standard tell.
    const extendsList = [];
    const implementsList = [];
    if (kind === 'interface' || kind === 'enum') {
      // Interface inheritance + enum base type — keep as `extends`.
      for (const t of inheritList) extendsList.push(t);
    } else {
      for (let i = 0; i < inheritList.length; i++) {
        const t = inheritList[i];
        if (i === 0 && !/^I[A-Z]/.test(t)) extendsList.push(t);
        else implementsList.push(t);
      }
    }

    const attributes = [...attrBlock.matchAll(/\[\s*([A-Za-z_][\w.]*)/g)].map((x) => x[1]);

    // Public fields / auto-properties — `public Foo Bar { get; }` or `public Foo Bar;`.
    const bodyStart = m.index + m[0].length;
    const body = sliceBalanced(text, bodyStart - 1);
    const fieldRe = /^\s*(?:public\s+|protected\s+internal\s+)(?:static\s+|readonly\s+|virtual\s+|override\s+|abstract\s+)*([A-Za-z_][\w.<>,\s\[\]?]*?)\s+([A-Za-z_]\w*)\s*[{;=]/gm;
    const fields = [];
    let fm;
    while ((fm = fieldRe.exec(body)) !== null) {
      const fieldType = normalizeTypeRef(fm[1]);
      const fieldName = fm[2];
      // Skip method matches (those have `(` after the name).
      const after = body.slice(fm.index + fm[0].length - 1, fm.index + fm[0].length + 4);
      if (after.startsWith('(')) continue;
      // Skip C# language keywords accidentally matched as types.
      if (/^(void|return|new|if|for|while|switch|using|class|struct|interface|enum|record)$/.test(fieldType)) continue;
      fields.push({ name: fieldName, type: fieldType });
    }

    out.push({ name, kind, extends: extendsList, implements: implementsList, fields, namespace, attributes });
  }
  return out;
}

function extractClassesCpp(text) {
  const out = [];
  // C++ `class|struct Name : public Base, virtual private Other { ... }`.
  const re = /^(?:template\s*<[^>]*>\s*)?(class|struct)\s+([A-Za-z_]\w*)(?:\s*:\s*([^\{]+?))?\s*\{/gm;
  let m;
  while ((m = re.exec(text)) !== null) {
    const kind = m[1];
    const name = m[2];
    const inheritList = m[3]
      ? splitTypeList(m[3]).map((t) => t.replace(/^(public|protected|private|virtual)\s+/g, '').replace(/^(public|protected|private|virtual)\s+/g, '').trim())
      : [];
    // C++ doesn't distinguish extends vs implements at the language level. Surface as extends.
    out.push({ name, kind, extends: inheritList, implements: [], fields: [], namespace: '', attributes: [] });
  }
  return out;
}

// `Foo<A,B>, IBar, Baz` → ['Foo<A,B>', 'IBar', 'Baz']  (commas inside <> not split)
function splitTypeList(s) {
  const out = [];
  let depth = 0;
  let buf = '';
  for (const c of s) {
    if (c === '<' || c === '(' || c === '[') depth++;
    else if (c === '>' || c === ')' || c === ']') depth--;
    if (c === ',' && depth === 0) {
      const t = buf.trim();
      if (t) out.push(t);
      buf = '';
    } else buf += c;
  }
  const t = buf.trim();
  if (t) out.push(t);
  return out;
}

// Strip generic parameters / array brackets / nullability for plain identifier graphing.
// Keeps the head identifier: `Func<Task<object>>` → `Func`. `IReadOnlyList<string>` → `IReadOnlyList`.
function normalizeTypeRef(t) {
  return t.trim().replace(/<.*$/, '').replace(/[\[\]?!]/g, '').trim();
}

// Read text from `text[fromIndex]` (which must be `{`) to its matching `}`. Returns the inside.
function sliceBalanced(text, fromIndex) {
  if (text[fromIndex] !== '{') return '';
  let depth = 0;
  for (let i = fromIndex; i < text.length; i++) {
    const c = text[i];
    if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) return text.slice(fromIndex + 1, i);
    }
  }
  return text.slice(fromIndex + 1);
}

function extractImports(text, lang) {
  const targets = [];
  if (lang === 'ts' || lang === 'tsx') {
    const re1 = /\b(?:import|export)\s+(?:[^'"`;]+\s+from\s+)?['"]([^'"]+)['"]/g;
    const re2 = /\brequire\s*\(\s*['"]([^'"]+)['"]\s*\)/g;
    let m;
    while ((m = re1.exec(text)) !== null) targets.push(m[1]);
    while ((m = re2.exec(text)) !== null) targets.push(m[1]);
  } else if (lang === 'csharp') {
    const re = /^using\s+([A-Za-z_][\w.]*)\s*;/gm;
    let m;
    while ((m = re.exec(text)) !== null) targets.push(m[1]);
  } else if (lang === 'cpp-header' || lang === 'cpp-impl') {
    const reQuoted = /^#include\s+"([^"]+)"/gm;
    const reAngle = /^#include\s+<([^>]+)>/gm;
    let m;
    while ((m = reQuoted.exec(text)) !== null) targets.push(m[1]);
    while ((m = reAngle.exec(text)) !== null) targets.push(m[1]);
  } else if (lang === 'python') {
    const re1 = /^\s*import\s+([A-Za-z_][\w.]*)/gm;
    const re2 = /^\s*from\s+([A-Za-z_.][\w.]*)\s+import\s+/gm;
    let m;
    while ((m = re1.exec(text)) !== null) targets.push(m[1]);
    while ((m = re2.exec(text)) !== null) targets.push(m[1]);
  }
  return targets;
}

// A file's module name (modules.mjs): its deepest sub-project or `## Modules` folder, else its
// top-level folder. Set once per run in main(), after the walk.
let moduleOf = makeModuleOf([]);

// Returns { rel, mod } when the import resolves to an in-repo file path,
// or { mod } when only the top-level module can be inferred,
// or null when the import is external/unresolvable.
function resolveImport(target, sourceRel, topLevelDirs, fileIndex) {
  // 0. C# namespace — `using Foo.Bar.Baz;` names a namespace, not a path. Resolve it
  //    against the namespace→file index built from each .cs file's `namespace` decl.
  //    A `using` imports a whole namespace, so the honest edge is module-level; a
  //    file-level edge is only emitted when the namespace maps to exactly one file.
  //    Match the longest known namespace that prefixes the target so a `using` on a
  //    leaf namespace still resolves when only an ancestor namespace is declared.
  if (fileIndex.byNamespace && fileIndex.byNamespace.size && !target.startsWith('.') && !target.includes('/')) {
    let nsHit = null;
    for (let ns = target; ns.includes('.'); ns = ns.slice(0, ns.lastIndexOf('.'))) {
      if (fileIndex.byNamespace.has(ns)) { nsHit = ns; break; }
    }
    if (!nsHit && fileIndex.byNamespace.has(target)) nsHit = target;
    if (nsHit) {
      const files = fileIndex.byNamespace.get(nsHit);
      const mod = moduleOf(files[0]);
      // Only a single-file namespace yields an unambiguous file edge.
      if (files.length === 1) return { rel: files[0], mod };
      return { mod };
    }
    // A dotted target that resolves to no known namespace is an external package
    // (System.*, third-party) — fall through to the basename branch, which returns null.
  }
  // 1. Relative path — resolve against source dir.
  if (target.startsWith('.')) {
    const sourceDir = path.posix.dirname(sourceRel);
    const resolved = path.posix.normalize(path.posix.join(sourceDir, target));
    const hit = matchAgainstIndex(resolved, fileIndex);
    if (hit) return { rel: hit, mod: moduleOf(hit) };
    // matchAgainstIndex only knows TS/JS extensions. For other languages whose relative
    // imports are extensionless (Ruby `require_relative "../core/shape"`, Python `.shape`),
    // try the path's last segment as a file basename across all indexed extensions before
    // degrading to a module-level edge — so a concrete FILE edge survives.
    const ext = resolveExtensionlessPath(resolved, sourceRel, fileIndex, topLevelDirs);
    if (ext && ext.rel) return ext;
    return { mod: moduleOf(resolved) };
  }
  // 2. Path with separator — try as repo-relative.
  if (target.includes('/')) {
    const hit = matchAgainstIndex(target, fileIndex);
    if (hit) return { rel: hit, mod: moduleOf(hit) };
    // Match basename suffix — e.g. `openxr/openxr.h` finds `include/openxr/openxr.h`.
    const suffixHit = fileIndex.bySuffix.get(target);
    if (suffixHit && suffixHit.length === 1) return { rel: suffixHit[0], mod: moduleOf(suffixHit[0]) };
    // Extensionless module path (Python `core/shape`, Go `proj/core`, Java `geo/core/Shape`):
    // try the path's last segments as a file basename across known extensions. Preferred over
    // the head-segment directory match below so a concrete FILE edge beats a folder edge.
    const ext = resolveExtensionlessPath(target, sourceRel, fileIndex, topLevelDirs);
    if (ext && ext.rel) return ext;
    // Head segment names a known top-level module → module-level edge.
    const headSegment = target.split('/')[0];
    const candidate = headSegment + '/';
    if (topLevelDirs.has(candidate)) return { mod: candidate };
    if (ext) return ext; // module-level fallback from the extensionless resolver
    return null;
  }
  // 3. Bare filename — look up by basename. Prefer same-module disambiguation.
  const base = target;
  let candidates = fileIndex.byBasename.get(base);
  // Extensionless bare module (e.g. a single-segment import): match basename sans extension.
  if (!candidates || !candidates.length) {
    const noExt = fileIndex.byBasenameNoExt && fileIndex.byBasenameNoExt.get(base);
    if (noExt && noExt.length) candidates = noExt;
  }
  if (!candidates || !candidates.length) return null;
  if (candidates.length === 1) return { rel: candidates[0], mod: moduleOf(candidates[0]) };
  const sourceMod = moduleOf(sourceRel);
  const sameModule = candidates.find((c) => moduleOf(c) === sourceMod);
  if (sameModule) return { rel: sameModule, mod: sourceMod };
  return { rel: candidates[0], mod: moduleOf(candidates[0]) };
}

function matchAgainstIndex(rel, fileIndex) {
  if (fileIndex.byRel.has(rel)) return rel;
  // ESM TS sources import the *compiled* `.js` form even when the source is `.ts` —
  // `import './envelope.js'` resolves to `envelope.ts`. Strip the suffix and re-try.
  const stripped = rel.replace(/\.(?:js|jsx|mjs|cjs)$/, '');
  const candidates = stripped !== rel ? [stripped, rel] : [rel];
  for (const base of candidates) {
    for (const ext of ['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs']) {
      if (fileIndex.byRel.has(base + ext)) return base + ext;
      if (fileIndex.byRel.has(base + '/index' + ext)) return base + '/index' + ext;
    }
  }
  return null;
}

// Resolve an extensionless, `/`-separated module path (e.g. `core/shape`, `geo/core/Shape`)
// to an in-repo file. Strategy: walk the path's tails from longest to shortest, matching the
// basename (without extension) of the final segment, constrained by the preceding segment as
// a directory hint. Falls back to a directory (module-level) edge when only a folder matches.
function resolveExtensionlessPath(target, sourceRel, fileIndex, topLevelDirs) {
  const segs = target.split('/').filter(Boolean);
  if (!segs.length) return null;
  // Try the last segment as a file basename (sans extension). Disambiguate by requiring the
  // parent dir segment to appear in the file's path when more than one candidate matches.
  const last = segs[segs.length - 1];
  const parent = segs.length >= 2 ? segs[segs.length - 2] : null;
  const byNoExt = fileIndex.byBasenameNoExt.get(last);
  if (byNoExt && byNoExt.length) {
    let cands = byNoExt;
    if (cands.length > 1 && parent) {
      const narrowed = cands.filter((r) => r.split('/').includes(parent));
      if (narrowed.length) cands = narrowed;
    }
    if (cands.length === 1) return { rel: cands[0], mod: moduleOf(cands[0]) };
    // Multiple: prefer same module as the source, else module-level edge to the first.
    const srcMod = moduleOf(sourceRel);
    const same = cands.find((r) => moduleOf(r) === srcMod);
    if (same) return { rel: same, mod: srcMod };
    return { mod: moduleOf(cands[0]) };
  }
  // No file basename matched — the last segment may name a package DIRECTORY (Go/Java
  // style). If exactly one indexed file lives directly under a dir of that name, treat it
  // as the file edge; otherwise fall back to a module-level edge.
  const dirHit = fileIndex.byDir.get(last);
  if (dirHit && dirHit.length === 1) return { rel: dirHit[0], mod: moduleOf(dirHit[0]) };
  if (dirHit && dirHit.length > 1) return { mod: moduleOf(dirHit[0]) };
  // Else try each segment as a top-level directory (module edge).
  for (const s of segs) {
    if (topLevelDirs.has(s + '/')) return { mod: s + '/' };
  }
  return null;
}

// `namespaceByRel` (optional) maps `rel` → declared namespace string, used to build the
// C# namespace→files index that `resolveImport` consults for `using` directives.
function buildFileIndex(files, namespaceByRel) {
  const byRel = new Set();
  const byBasename = new Map();
  const byBasenameNoExt = new Map();
  const byDir = new Map(); // immediate-parent-dir name → files directly within it
  const bySuffix = new Map();
  const byNamespace = new Map();
  for (const f of files) {
    byRel.add(f.rel);
    const base = path.posix.basename(f.rel);
    if (!byBasename.has(base)) byBasename.set(base, []);
    byBasename.get(base).push(f.rel);
    const baseNoExt = base.replace(/\.[^.]+$/, '');
    if (!byBasenameNoExt.has(baseNoExt)) byBasenameNoExt.set(baseNoExt, []);
    byBasenameNoExt.get(baseNoExt).push(f.rel);
    // Index two- and three-segment suffixes so `openxr/openxr.h` matches `include/openxr/openxr.h`.
    const parts = f.rel.split('/');
    if (parts.length >= 2) {
      const dirName = parts[parts.length - 2];
      if (!byDir.has(dirName)) byDir.set(dirName, []);
      byDir.get(dirName).push(f.rel);
    }
    for (let depth = 2; depth <= 3 && depth <= parts.length; depth++) {
      const suf = parts.slice(parts.length - depth).join('/');
      if (!bySuffix.has(suf)) bySuffix.set(suf, []);
      bySuffix.get(suf).push(f.rel);
    }
    const ns = namespaceByRel && namespaceByRel.get(f.rel);
    if (ns) {
      if (!byNamespace.has(ns)) byNamespace.set(ns, []);
      byNamespace.get(ns).push(f.rel);
    }
  }
  return { byRel, byBasename, byBasenameNoExt, byDir, bySuffix, byNamespace };
}

// Entry points of the project and of each nested module with a manifest: package.json
// `main`/`module`/`bin` (build output mapped back to source), csproj StartupObject, and
// `src/main.*`/`src/index.*` at a module's root. `toSource(rel)` maps a manifest path to an indexed
// source file or null; paths that resolve to nothing are left out.
function detectEntryPoints(root, files, moduleRoots, toSource) {
  const indexed = new Set(files.map((f) => f.rel));
  const entries = [];
  const fromManifest = (rel, role) => {
    const src = toSource(path.posix.normalize(rel));
    if (src) entries.push({ rel: src, role });
  };
  for (const dir of ['', ...moduleRoots.map((r) => r.dir)]) {
    const pkgRel = dir + 'package.json';
    if (!indexed.has(pkgRel)) continue;
    try {
      const j = JSON.parse(fs.readFileSync(path.join(root, pkgRel), 'utf8').replace(/^\uFEFF/, ''));
      const tag = dir ? `${pkgRel} ` : 'package.json ';
      for (const key of ['main', 'module']) {
        if (typeof j[key] === 'string') fromManifest(dir + j[key], tag + key);
      }
      if (j.bin) {
        const bins = typeof j.bin === 'string' ? { [j.name || 'bin']: j.bin } : j.bin;
        for (const [k, v] of Object.entries(bins)) if (typeof v === 'string') fromManifest(dir + v, `bin: ${k}`);
      }
    } catch {}
  }
  for (const cs of files.filter((f) => f.rel.endsWith('.csproj'))) {
    try {
      const text = fs.readFileSync(cs.abs, 'utf8');
      const m = text.match(/<StartupObject>([^<]+)<\/StartupObject>/);
      if (m) entries.push({ rel: cs.rel, role: `StartupObject: ${m[1]}` });
    } catch {}
  }
  for (const f of files) {
    if (/(?:^|\/)(Program|Main)\.cs$/i.test(f.rel)) entries.push({ rel: f.rel, role: 'C# entry' });
    const owner = moduleRoots.find((r) => f.rel.startsWith(r.dir)); // deepest first
    const rest = owner ? f.rel.slice(owner.dir.length) : f.rel;
    if (/^src\/(main|index)\.(ts|tsx|js|jsx|mjs)$/.test(rest)) entries.push({ rel: f.rel, role: 'SPA entry' });
  }
  const seen = new Set();
  return entries.filter((e) => { if (seen.has(e.rel)) return false; seen.add(e.rel); return true; });
}

// Commits per file over the last ACTIVITY_DAYS and the date of the latest one, from one
// `git log`. Paths are relative to `root` (`--relative`). Empty outside git or on error.
const ACTIVITY_DAYS = 90;
const ACTIVITY_TOP = 12;
function gitActivity(root) {
  const activity = new Map();
  let text;
  try {
    text = execFileSync('git', ['log', `--since=${ACTIVITY_DAYS}.days.ago`, '--no-merges', '--relative', '--name-only', '--format=%x00%cs'],
      { cwd: root, encoding: 'utf8', timeout: 15000, maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    return activity;
  }
  for (const commit of text.split('\0')) {
    const lines = commit.split('\n').map((l) => l.trim()).filter(Boolean);
    const date = lines.shift();
    for (const rel of new Set(lines)) {
      const a = activity.get(rel);
      if (a) a.commits++;
      else activity.set(rel, { commits: 1, last: date });
    }
  }
  return activity;
}

// rel → names a file defines: functions and methods, exports, classes and their methods.
function buildSymbolsByFile(fileDefines, groups) {
  const symbolsByFile = new Map();
  const add = (rel, name) => {
    if (!name) return;
    if (!symbolsByFile.has(rel)) symbolsByFile.set(rel, new Set());
    symbolsByFile.get(rel).add(name);
  };
  for (const [rel, defs] of fileDefines.entries()) for (const d of defs) add(rel, d);
  for (const items of groups.values()) for (const it of items) {
    for (const ex of (it.exports || [])) add(it.rel, ex.name.replace(/^default:\s+/, '').replace(/\s+—\s+.*$/, '').trim());
    for (const c of (it.classes || [])) {
      add(it.rel, c.name);
      for (const m of (c.methods || [])) add(it.rel, m);
    }
  }
  return symbolsByFile;
}

// Names a file uses from elsewhere: the callees of its calls and the types its classes
// extend, implement or hold. Used to pick, among a package's or namespace's files, the
// ones an import really depends on.
function usedNames(rel, fileCalls, groups) {
  const used = new Set();
  for (const e of fileCalls.get(rel) || []) used.add(e.callee);
  const items = groups.get(moduleOf(rel)) || [];
  const it = items.find((x) => x.rel === rel);
  for (const c of (it && it.classes) || []) {
    for (const t of [...(c.extends || []), ...(c.implements || []), ...(c.fields || []).map((f) => f.type)]) if (t) used.add(normalizeTypeRef(t));
  }
  return used;
}

// `from <dots><path> import <name>`: the submodule file `<path>/<name>.py` (or its package
// `__init__.py`), relative to the source's folder for leading dots, else to the repo root
// or `src/`. Exact matches only.
function resolvePyFrom(spec, sourceRel, byRel) {
  const dots = spec.match(/^\.*/)[0].length;
  const tail = spec.slice(dots);
  let bases = ['', 'src'];
  if (dots) {
    let dir = path.posix.dirname(sourceRel);
    for (let i = 1; i < dots; i++) dir = path.posix.dirname(dir);
    bases = [dir === '.' ? '' : dir];
  }
  for (const b of bases) {
    const p = b ? `${b}/${tail}` : tail;
    for (const c of [`${p}.py`, `${p}/__init__.py`]) if (byRel.has(c) && c !== sourceRel) return c;
  }
  return null;
}

// Writes `text` through a temp file and a rename, so a reader never sees half a file.
// Same content: leaves the file alone but moves its mtime, so staleness checks (which
// compare file mtimes with the codemap's) see it as current. Returns true when written.
function writeIfChanged(file, text) {
  let prev = null;
  try { prev = fs.readFileSync(file, 'utf8'); } catch { /* first write */ }
  if (prev === text) {
    const now = new Date();
    fs.utimesSync(file, now, now);
    return false;
  }
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
  return true;
}

const DECL_WORDS = 'class|struct|interface|enum|record|trait|type|def|fn|func|function|const|let|var|val|protocol|object|module|namespace|union|typedef';

// 1-based line of `name`'s declaration: the first line with a declaration keyword before
// it, else the first line that mentions it. Null when the text never names it.
function declarationLine(lines, name) {
  const esc = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const decl = new RegExp(`\\b(?:${DECL_WORDS})\\s+\\*?${esc}(?![\\w$])`);
  const any = new RegExp(`(?:^|[^\\w$])${esc}(?![\\w$])`);
  let first = null;
  for (let i = 0; i < lines.length; i++) {
    if (decl.test(lines[i])) return i + 1;
    if (first === null && any.test(lines[i])) first = i + 1;
  }
  return first;
}

// A file's outline: the AST's classes and functions (with line ranges), plus each export
// and class the AST didn't place, located by text. Exports are marked `exported` and keep
// their signature. Sorted by line.
function buildSymbols(astSymbols, exports, classes, text) {
  const symbols = astSymbols.map((s) => ({ ...s }));
  const byName = new Map();
  for (const s of symbols) if (!byName.has(s.name)) byName.set(s.name, s);
  let lines = null;
  const place = (name, kind) => {
    lines = lines || text.split(/\r?\n/);
    const line = declarationLine(lines, name);
    const s = { name, kind, ...(line ? { line } : {}) };
    symbols.push(s);
    byName.set(name, s);
    return s;
  };
  for (const c of classes || []) if (c.name && !byName.has(c.name)) place(c.name, c.kind || 'class');
  for (const e of exports || []) {
    const [bare, ...sig] = e.name.replace(/^default:\s+/, '').split(' — ');
    const name = bare.trim();
    if (!name || /\s/.test(name) || name.startsWith('<')) continue;
    const s = byName.get(name) || place(name, 'export');
    s.exported = true;
    const signature = sig.join(' — ').trim();
    if (signature) s.signature = signature;
  }
  return symbols.sort((a, b) => (a.line ?? Infinity) - (b.line ?? Infinity) || a.name.localeCompare(b.name));
}

// The machine-readable codemap: per-file data (language, size, lines, content hash,
// purpose, outline, resolved imports and importers, tests that reach the file, git
// activity), module edges, every class and every in-scope call edge. Deterministic: no
// timestamps beyond the day, keys in sorted order.
function buildCodemapJson({ projectName, today, groups, sortedGroups, fileEdges, refEdges, moduleEdges, manifestByModule, projectsByModule, allClassEntries, jsonCalls, jsonCallSeq, activity, entryPoints }) {
  const rev = new Map();
  for (const [src, targets] of fileEdges.entries()) {
    for (const t of targets) {
      if (!rev.has(t)) rev.set(t, new Set());
      rev.get(t).add(src);
    }
  }
  const refBy = new Map();
  for (const [src, targets] of refEdges.entries()) {
    for (const t of targets) {
      if (!refBy.has(t)) refBy.set(t, new Set());
      refBy.get(t).add(src);
    }
  }
  const files = {};
  for (const g of sortedGroups) {
    for (const it of [...groups.get(g)].sort((a, b) => a.rel.localeCompare(b.rel))) {
      const a = activity.get(it.rel);
      // The nearest tests only: in a big repo a shared file can reach thousands of tests.
      const reached = isTest(it.rel) ? [] : reach(rev, [it.rel]).tests;
      const tests = reached.sort((x, y) => x.via.length - y.via.length || x.file.localeCompare(y.file))
        .slice(0, TESTS_PER_FILE).map((t) => t.file).sort();
      files[it.rel] = {
        lang: JS_EXTS.has(path.extname(it.rel).toLowerCase()) ? 'js' : (LANG_BY_EXT[path.extname(it.rel).toLowerCase()] || 'other'),
        size: it.size,
        lines: it.lines,
        hash: it.hash,
        purpose: it.purpose,
        module: g,
        ...(it.vendored ? { vendored: true } : {}),
        ...(isTest(it.rel) ? { isTest: true } : {}),
        symbols: it.symbols || [],
        imports: [...(fileEdges.get(it.rel) || [])].sort(),
        importedBy: [...(rev.get(it.rel) || [])].sort(),
        tests,
        ...(reached.length > tests.length ? { testsTotal: reached.length } : {}),
        ...(refEdges.has(it.rel) ? { refs: [...refEdges.get(it.rel)].sort() } : {}),
        ...(refBy.has(it.rel) ? { referencedBy: [...refBy.get(it.rel)].sort() } : {}),
        ...(a ? { commits: a.commits, lastChange: a.last } : {}),
      };
    }
  }
  const modules = {};
  for (const m of [...new Set([...sortedGroups, ...moduleEdges.keys()])].sort()) {
    const deps = moduleEdges.get(m) || new Map();
    modules[m] = {
      ...(manifestByModule.has(m) ? { manifest: manifestByModule.get(m) } : {}),
      ...(projectsByModule.has(m) ? { projects: projectsByModule.get(m) } : {}),
      dependsOn: Object.fromEntries([...deps.entries()].sort((x, y) => x[0].localeCompare(y[0]))),
    };
  }
  const classes = [...allClassEntries]
    .sort((a, b) => a.file.localeCompare(b.file) || a.name.localeCompare(b.name))
    .map(({ module, ...c }) => c);
  const calls = [...jsonCalls].sort((a, b) => a.file.localeCompare(b.file) || a.caller.localeCompare(b.caller) || a.callee.localeCompare(b.callee));
  const callSequences = [...jsonCallSeq].sort((a, b) => a.file.localeCompare(b.file) || a.caller.localeCompare(b.caller));
  return { version: 1, project: projectName, updated: today, entryPoints, files, modules, classes, calls, callSequences };
}

// Parse many files at once: worker threads each run tree-sitter on part of `jobs`
// ({ rel, abs, lang }). Returns rel → extraction result (null when the parser declined).
// A worker that fails leaves its files out, and the caller parses those on the main thread.
const PARALLEL_MIN_JOBS = 64;
async function extractInParallel(jobs) {
  const results = new Map();
  const cores = os.availableParallelism?.() ?? os.cpus().length; // availableParallelism needs Node 18.14+
  const count = Math.min(cores - 1, 8, Math.ceil(jobs.length / 32));
  if (jobs.length < PARALLEL_MIN_JOBS || count < 2) return results;
  let next = 0;
  const runWorker = () => new Promise((resolve) => {
    let worker;
    try {
      worker = new Worker(new URL('./extract-worker.mjs', import.meta.url));
    } catch {
      resolve();
      return;
    }
    const send = () => {
      if (next >= jobs.length) { worker.terminate().then(resolve, resolve); return; }
      const id = next++;
      worker.postMessage({ id, abs: jobs[id].abs, lang: jobs[id].lang });
    };
    worker.on('message', ({ id, result, error }) => {
      if (!error) results.set(jobs[id].rel, result);
      send();
    });
    worker.on('error', () => resolve());
    worker.on('exit', () => resolve()); // a worker can exit with no error event
    send();
  });
  await Promise.all(Array.from({ length: count }, runWorker));
  return results;
}

