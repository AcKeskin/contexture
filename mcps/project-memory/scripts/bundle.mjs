#!/usr/bin/env node
// Bundle the server and its dependencies into one committed file,
// dist/project-memory.cjs, so a plugin install runs it with plain `node`, no
// npm install or tsc. The banner holds a hash of the inputs; --check compares
// it without esbuild, so CI and the plugin build can catch a stale bundle.
//
// Usage:
//   npm run bundle                      # rebuild dist/project-memory.cjs
//   node scripts/bundle.mjs --check     # exit 1 if src changed since the bundle

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist', 'project-memory.cjs');
const INPUTS = ['src', 'package-lock.json'];

function files(rel) {
  const abs = path.join(ROOT, rel);
  if (!fs.statSync(abs).isDirectory()) return [rel];
  return fs
    .readdirSync(abs)
    .sort()
    .flatMap((name) => files(path.posix.join(rel, name)));
}

function inputHash() {
  const hash = createHash('sha256');
  for (const rel of INPUTS.flatMap(files)) {
    hash.update(rel + '\0');
    hash.update(fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n'));
  }
  return hash.digest('hex').slice(0, 16);
}

const banner = `// project-memory MCP bundle. Generated by scripts/bundle.mjs; do not edit. src-hash: ${inputHash()}`;

if (process.argv.includes('--check')) {
  const head = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').split('\n', 3).map((l) => l.trimEnd()) : [];
  if (!head.includes(banner)) {
    console.error('stale: mcps/project-memory/dist/project-memory.cjs');
    console.error('run: cd mcps/project-memory && npm ci && npm run bundle');
    process.exit(1);
  }
  process.exit(0);
}

const { build } = await import('esbuild');
await build({
  entryPoints: [path.join(ROOT, 'src', 'index.ts')],
  outfile: OUT,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node18',
  banner: { js: banner },
  legalComments: 'none',
  logLevel: 'warning',
});
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
